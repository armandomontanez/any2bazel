"""What one C# compile of an MSBuild build consists of, for the report.

A csc command line of an SDK-style project is several hundred arguments, most
of them framework reference assemblies. What a BUILD author (or the emitter)
needs from it is much smaller, and is mostly about WHERE each input comes from:

  * sources: hand-written, or written by the build (and by which mechanism);
  * references and analyzers: a framework pack, a NuGet package (which asset),
    another project of the build, the SDK itself, or a loose file;
  * the other files that steer the compile (additional files, analyzer
    configs) and what gets embedded (resources).

Everything here is a pure function of the command line plus a few facts the
extractor already has (which project writes which assembly, which files git
tracks), so it runs anywhere.
"""

from __future__ import annotations

import hashlib
import ntpath
import os
import re
from typing import Callable, Dict, Iterable, List, Optional, Sequence, Tuple

import canonicalize_csc as csc_dialect

# How MSBuild-written sources are recognized. The first group are files every
# SDK-style project gets; a Bazel build restates them (see the templates).
_GENERATED_KINDS = (
    (re.compile(r"\.AssemblyInfo\.cs$", re.I), "assembly_info"),
    (re.compile(r"\.AssemblyAttributes\.cs$", re.I), "target_framework_attribute"),
    (re.compile(r"\.GlobalUsings\.g\.cs$", re.I), "global_usings"),
    (re.compile(r"(MicrosoftTestingPlatformEntryPoint|SelfRegisteredExtensions|"
                r"TestingPlatformEntryPoint|TestPlatformEntryPoint|AutoGeneratedProgram)[^/]*\.cs$", re.I),
     "test_entry_point"),
    (re.compile(r"/Generated Files/CsWinRT/", re.I), "cswinrt_projection"),
    (re.compile(r"\.g(\.i)?\.cs$", re.I), "xaml_or_generator_output"),
    (re.compile(r"\.Designer\.cs$", re.I), "designer"),
)
_PACKS = re.compile(r"/dotnet/packs/", re.I)
_SDK = re.compile(r"/dotnet/sdk/(?P<ver>\d[^/]*)/(?P<rel>.*)$", re.I)
_NETFX = re.compile(r"/Reference Assemblies/Microsoft/Framework/\.NETFramework/(?P<ver>v[\d.]+)/(?P<rel>.*)$",
                    re.I)
_NUGET_CACHE = re.compile(r"/\.nuget/packages/(?P<id>[^/]+)/(?P<ver>\d[^/]*)/(?P<rel>.+)$", re.I)
_MAX_HASHED = 256 * 1024


def _posix(path: str) -> str:
    return path.replace("\\", "/")


def classify_external(path: str) -> Optional[dict]:
    """Where a file outside the repository comes from, read off its path:
    a NuGet package, an SDK pack, the SDK itself, or the .NET Framework
    reference assemblies. None if it is none of those."""
    p = "/" + _posix(path).lstrip("/")
    m = _SDK.search(p)
    if m:
        return {"kind": "sdk", "version": m.group("ver"), "path": m.group("rel")}
    m = _NETFX.search(p)
    if m:
        return {"kind": "pack", "id": "Microsoft.NETFramework.ReferenceAssemblies",
                "version": m.group("ver"), "path": m.group("rel")}
    m = _NUGET_CACHE.search(p)
    if m:
        # Anything in a package of the global packages folder, wherever in the
        # package it sits (a tool at its root, a source under build/).
        return {"kind": "pack" if csc_dialect.is_framework_pack(m.group("id")) else "nuget",
                "id": m.group("id").lower(), "version": m.group("ver"), "path": m.group("rel")}
    pkg = csc_dialect.package_of(p)
    if pkg is None:
        return None
    marker = "/%s/" % pkg[1]
    rel = p[p.lower().rfind(marker.lower()) + len(marker):] if marker.lower() in p.lower() else ""
    if not rel:                                 # packages.config layout: <Id>.<Version>/...
        marker = ".%s/" % pkg[1]
        rel = p[p.lower().rfind(marker.lower()) + len(marker):]
    kind = "pack" if _PACKS.search(p) or csc_dialect.is_framework_pack(pkg[0]) else "nuget"
    return {"kind": kind, "id": pkg[0], "version": pkg[1], "path": rel}


def generated_kind(repo_relative: str) -> str:
    probe = "/" + _posix(repo_relative)
    for pattern, kind in _GENERATED_KINDS:
        if pattern.search(probe):
            return kind
    return "generated"


def _sha256(path: str) -> str:
    try:
        if os.path.getsize(path) > _MAX_HASHED:
            return ""
        with open(path, "rb") as f:
            return hashlib.sha256(f.read()).hexdigest()
    except OSError:
        return ""


def _collapse(entries: List[dict]) -> List[dict]:
    """Generated trees can hold hundreds of files (a WinRT projection). Report
    a kind with many files as one entry per directory."""
    out: List[dict] = []
    by_dir: Dict[Tuple[str, str], List[str]] = {}
    for e in entries:
        if e["kind"] == "cswinrt_projection":
            by_dir.setdefault((e["kind"], _posix(e["path"]).rsplit("/", 1)[0]), []).append(e["path"])
        else:
            out.append(e)
    for (kind, directory), paths in sorted(by_dir.items()):
        out.append({"kind": kind, "dir": directory, "files": len(paths)})
    return out


def digest(args: Sequence[str], repo_root: str, cwd: str, *,
           is_generated: Callable[[str], bool],
           project_of: Callable[[str], Optional[str]],
           fs: bool = False, resource_sources: Optional[Dict[str, str]] = None) -> dict:
    """The report entry for one csc command line.

    `is_generated(absolute path)` says whether a file under the repo was
    written by the build; `project_of(absolute path)` names the target whose
    output an assembly path is (None if it is not a project's output).
    `resource_sources` maps a generated `.resources` file (absolute path,
    lower-case) to the repo-relative `.resx` it was compiled from.
    """
    view = csc_dialect.parse(args, repo_root, cwd=cwd)
    start = csc_dialect.compiler_index(args) + 1

    def absolute(tok: str) -> str:
        tok = tok.strip('"')
        if ntpath.isabs(tok) or tok.startswith("/"):
            return ntpath.normpath(tok) if ntpath.isabs(tok) else tok
        return ntpath.normpath(ntpath.join(cwd, tok))

    def under_repo(path: str) -> bool:
        return bool(repo_root) and _posix(path).lower().startswith(_posix(repo_root).lower().rstrip("/") + "/")

    def repo_rel(path: str) -> str:
        return _posix(path)[len(_posix(repo_root).rstrip("/")) + 1:]

    hand_written: List[str] = []
    generated: List[dict] = []
    external_sources: List[dict] = []
    # `packs` counts the files taken from each framework pack; `pack_files`
    # lists them and `pack_roots` says where on the machine the pack was: a
    # pack is a NuGet package the SDK unpacked, so its files can be locked.
    refs = {"packs": {}, "pack_files": {}, "pack_roots": {}, "nuget": [], "projects": [],
            "other": []}
    analyzers = {"packs": {}, "pack_files": {}, "pack_roots": {}, "nuget": [], "sdk": [],
                 "projects": [], "other": []}
    additional: List[dict] = []
    configs: List[dict] = []
    resources: List[dict] = []

    def place(raw: str) -> dict:
        path = absolute(raw)
        if under_repo(path):
            rel = repo_rel(path)
            owner = project_of(path)
            if owner:
                return {"kind": "project", "target": owner, "path": rel}
            return {"kind": "generated" if is_generated(path) else "repo", "path": rel}
        ext = classify_external(path)
        return ext if ext else {"kind": "other", "path": _posix(path)}

    for tok in args[start:]:
        if tok.startswith("@"):
            continue
        parsed = csc_dialect._option(tok)
        if parsed is None:
            if not tok.strip():
                continue
            where = place(tok)
            if where["kind"] == "repo":
                hand_written.append(where["path"])
            elif where["kind"] in ("generated", "project"):
                entry = {"kind": generated_kind(where["path"]), "path": where["path"]}
                if fs and entry["kind"] != "cswinrt_projection":
                    digest_ = _sha256(absolute(tok))
                    if digest_:
                        entry["sha256"] = digest_
                generated.append(entry)
            else:
                external_sources.append(where)
            continue
        name, value = parsed
        name = name.rstrip("+-")
        if not value:
            continue
        items = [v.strip().strip('"') for v in re.split(r"[;,]", value) if v.strip().strip('"')] \
            if name in ("reference", "link", "analyzer", "additionalfile", "analyzerconfig") else []
        if name in ("reference", "link", "analyzer"):
            bucket = refs if name != "analyzer" else analyzers
            for item in items:
                if "=" in item and not ntpath.splitdrive(item)[0]:
                    item = item.split("=", 1)[1]
                where = place(item)
                kind = where["kind"]
                if kind == "pack":
                    key = "%s/%s" % (where["id"], where["version"])
                    bucket["packs"][key] = bucket["packs"].get(key, 0) + 1
                    bucket["pack_files"].setdefault(key, []).append(where["path"])
                    full = _posix(absolute(item))
                    if full.lower().endswith("/" + where["path"].lower()):
                        bucket["pack_roots"][key] = full[:-len(where["path"]) - 1]
                elif kind == "nuget":
                    bucket["nuget"].append({k: where[k] for k in ("id", "version", "path")})
                elif kind == "project":
                    bucket["projects"].append({"target": where["target"], "path": where["path"]})
                elif kind == "sdk" and "sdk" in bucket:
                    bucket["sdk"].append(where["path"])
                else:
                    bucket["other"].append(where.get("path", item))
        elif name == "additionalfile":
            additional.extend(place(i) for i in items)
        elif name == "analyzerconfig":
            for item in items:
                where = place(item)
                if fs and where["kind"] == "generated":
                    digest_ = _sha256(absolute(item))
                    if digest_:
                        where["sha256"] = digest_
                configs.append(where)
        elif name in ("resource", "linkresource"):
            parts = [p.strip().strip('"') for p in value.split(",")]
            where = place(parts[0])
            resource = {"name": parts[1] if len(parts) > 1 and parts[1]
                        else ntpath.basename(parts[0].replace("/", "\\")),
                        "kind": where["kind"], "path": where.get("path", parts[0])}
            source = (resource_sources or {}).get(absolute(parts[0]).lower())
            if source:
                resource["from"] = source
            resources.append(resource)

    out: dict = {
        "assembly": view.assembly,
        "target": view.target,
        "defines": list(view.defines),
        "options": list(view.options),
        "sources": {"hand_written": sorted(hand_written, key=str.lower)},
        "references": {k: v for k, v in refs.items() if v},
        "analyzers": {k: v for k, v in analyzers.items() if v},
    }
    if generated:
        out["sources"]["generated"] = _collapse(generated)
    if external_sources:
        out["sources"]["external"] = external_sources
    if additional:
        out["additional_files"] = additional
    if configs:
        out["analyzer_configs"] = configs
    if resources:
        out["resources"] = resources
    version = csc_dialect.sdk_version(view.compiler)
    if version:
        out["compiler_sdk"] = version
    return out


_NETFX_TFM = re.compile(r"^net[1-4]\d{1,2}$", re.I)       # net48, net472, net35


def rules_dotnet_name(assembly: str, path: str, project_dir: str) -> str:
    """The logical name rules_dotnet (0.22) gives a file listed in a target's
    `resources`: `<assembly>.<path below the package, dotted>`, or
    `<assembly>.<file name>` for a file outside it."""
    p, base = _posix(path), _posix(project_dir).rstrip("/")
    relative = p[len(base) + 1:] if base and p.lower().startswith(base.lower() + "/") \
        else p.rsplit("/", 1)[-1]
    return "%s.%s" % (assembly, relative.replace("/", "."))


def rules_dotnet_gaps(d: dict, project_dir: str = "") -> List[str]:
    """Why rules_dotnet's own compile rules cannot reproduce the compile a
    digest describes; empty if they can. Such a target is compiled by the
    exact-command-line template instead (`csc_assembly.bzl`), and takes even
    its framework pack from the lock.

    Each entry is a property of rules_dotnet 0.22.2 that was hit on a real
    project, not a guess:
      * .NET Framework: it passes every assembly of the reference pack, MSBuild
        the ones the project references (plus facades). The extras change what
        names bind to.
      * ASP.NET Core: `project_sdk = "web"` passes every analyzer of the pack,
        including source generators MSBuild only runs when the project enables
        them.
      * Embedded resources: always named `<assembly>.<path>`; MSBuild names
        them `<RootNamespace>.<path>` (or as `LogicalName` says)."""
    gaps: List[str] = []
    tfm = (d.get("target_framework") or "").split("-")[0]
    if _NETFX_TFM.match(tfm):
        gaps.append(".NET Framework target: rules_dotnet passes its whole reference pack, "
                    "MSBuild a part of it")
    if any(p.lower().startswith("microsoft.aspnetcore.app.ref")
           for p in d.get("references", {}).get("packs", {})):
        gaps.append("ASP.NET Core: rules_dotnet's web SDK passes every analyzer of the pack, "
                    "MSBuild the ones the project enables")
    prefix = d.get("assembly", "") + "."
    odd = []
    for r in d.get("resources", []):
        if r.get("from", "").lower().endswith(".resx"):
            # Converted by a rule of ours, whose output can be named freely.
            expressible = r["name"].startswith(prefix)
        else:
            expressible = r.get("kind") == "repo" and \
                r["name"] == rules_dotnet_name(d.get("assembly", ""), r.get("path", ""), project_dir)
        if not expressible:
            odd.append(r["name"])
    if odd:
        gaps.append("embedded resource %s%s: rules_dotnet names every resource "
                    "`<assembly>.<path>`" % (odd[0], " (and %d more)" % (len(odd) - 1)
                                             if len(odd) > 1 else ""))
    return gaps


def packages_used(digests: Iterable[dict]) -> Dict[Tuple[str, str], Dict[str, set]]:
    """(package id, version) -> {"compile": {...}, "analyzers": {...},
    "files": {...}}: every NuGet package file any compile named, from the
    digests of a whole build."""
    out: Dict[Tuple[str, str], Dict[str, set]] = {}

    def add(entry: dict, role: str) -> None:
        if entry.get("kind", "nuget") != "nuget" or "id" not in entry:
            return
        slot = out.setdefault((entry["id"], entry["version"]),
                              {"compile": set(), "analyzers": set(), "files": set()})
        slot[role].add(entry["path"])

    for d in digests:
        for e in d.get("references", {}).get("nuget", []):
            add(e, "compile")
        for e in d.get("analyzers", {}).get("nuget", []):
            add(e, "analyzers")
        for e in d.get("additional_files", []) + d.get("analyzer_configs", []) \
                + d.get("sources", {}).get("external", []):
            add(e, "files")
    return out
