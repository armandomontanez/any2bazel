"""Write rules_cc BUILD files for the C++ targets of an MSBuild build.

    python3 emit_cc.py <msbuild.report.json> <nuget_lock.json> <workspace> \\
        --reference-root DIR [--only NAME ...] [--generated-map FILE] [--dry-run]

Each C++ project of the report becomes a `cc_library` (static library) or a
`cc_binary` (executable, or DLL with `linkshared`), restating what the reference
build did:

  * sources and compiler options from the project's compile command lines;
  * the headers of the repository its compiles READ, from the compiler's
    tracking log. No project file lists them (an include directory is the whole
    declaration), and Bazel refuses a header nobody declared;
  * what it reads from elsewhere as dependencies: a vcpkg port, the headers of a
    NuGet package, the C++/WinRT projections its build generated;
  * its resource script (`windows_resources`, rc.bzl), its WinRT metadata and
    component projection (`winrt_winmd`, `cppwinrt_component`);
  * the link: libraries by name, other projects as labels, the module
    definition file, embedded manifests.

A file some project-specific build step generated (a version header, a resource
script made from translations) has no rule the emitter could know. Such a file
is copied from the reference tree into the workspace, at the path the build
read it from, and listed under `snapshots` in the summary: the build works, and
the file is a frozen copy until a rule replaces it. `--generated-map FILE`
names such rules (JSON list of {match, deps, file}; `match` is a fragment of
the generated file's path, `deps` the libraries that provide it as a header,
`file` its label where it is an input by itself).

It is a starting point, not an authority: run the diff on the result. What it
cannot express is listed per target under `unhandled` in the summary it prints
(and writes to `emit_cc.summary.json`), and such a target is not written.

Only files carrying its marker line are overwritten.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

from emit_dotnet import Workspace, _fmt_list, _posix, _sanitize, foreign_export_blocks

MARKER = "# Generated by any2bazel emit_cc.py"
EXPORTS_BEGIN = "# any2bazel:cc-exports begin (generated; do not edit between the markers)"
EXPORTS_END = "# any2bazel:cc-exports end"

SUMMARY = "emit_cc.summary.json"
PLATFORM_PACKAGE = "bazel/cppwinrt"
PLATFORM = "//%s:platform" % PLATFORM_PACKAGE
SDK_CONTRACTS = "@windows_sdk//:contract_winmds"

_RSP_TOKEN = re.compile(r'"([^"]*)"|(\S+)')
# cppwinrt options that take a value.
_CPPWINRT_VALUED = {"-in", "-input", "-ref", "-reference", "-out", "-output", "-comp",
                    "-component", "-name", "-pch", "-include", "-exclude", "-base"}
# What rules_cc compiles when it is listed in `srcs`.
_SOURCE_EXTENSIONS = (".cpp", ".cc", ".cxx", ".c++", ".c")
# Compiler options stated another way on a Bazel target.
_CRT = {"/MT": "static_link_msvcrt", "/MTd": "static_link_msvcrt", "/MD": "", "/MDd": ""}
# Linker options that are the target kind, or that the toolchain states.
_LINK_IMPLIED = ("/DLL", "/MACHINE:")
# Only meaningful when linking a managed image; ignored for a native one.
_LINK_MANAGED_ONLY = ("/ASSEMBLYRESOURCE:",)
# Linker options whose value is a file of the workspace.
_LINK_FILE = ("/MANIFESTINPUT:",)
_SYSTEM_ORIGINS = ("winsdk", "msvc", "vs", "system", "")


def _option_order(flag: str) -> int:
    """Compiler options whose effect depends on what follows them, first. The
    report lists options sorted, and `/std:c++latest` implies `/permissive-`
    for whatever `/permissive` came BEFORE it; `/permissive-` in turn implies
    `/Zc:` settings an explicit one has to follow."""
    low = flag.lower()
    return 0 if low.startswith("/std:") else 1 if low.startswith("/permissive") else 2


def _tokens(lines: Iterable[str]) -> List[str]:
    out: List[str] = []
    for line in lines:
        for m in _RSP_TOKEN.finditer(line):
            out.append(m.group(1) if m.group(1) is not None else m.group(2))
    return out


def _win(path: str) -> str:
    return path.replace("/", "\\")


def _quote(value: str) -> str:
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def _attr(name: str, values: Sequence[str], indent: int = 4) -> List[str]:
    """`name = [...],` or nothing for an empty list."""
    if not values:
        return []
    return ["%s%s = %s," % (" " * indent, name, _fmt_list(values, indent + 4))]


class Emitter:
    def __init__(self, report: dict, lock: dict, workspace_root: str,
                 reference_root: Optional[str] = None, nuget_repo: str = "nuget",
                 vcpkg_repo: str = "vcpkg", only: Optional[Sequence[str]] = None,
                 hooks: Optional[Sequence[dict]] = None, file_exists=os.path.isfile):
        self.report = report
        self.lock = lock
        self.root = workspace_root
        self.reference_root = _win(reference_root).rstrip("\\") if reference_root else ""
        self.nuget_repo = nuget_repo
        self.vcpkg_repo = vcpkg_repo
        self.only = set(only or [])
        self.hooks: List[dict] = list(hooks or [])
        self.file_exists = file_exists
        self.targets = {n: t for n, t in report.get("targets", {}).items()
                        if not t.get("csharp") and t.get("project", "").lower().endswith(".vcxproj")}
        self.package: Dict[str, str] = {}
        self.bazel_name: Dict[str, str] = {}
        for name, t in self.targets.items():
            project = _posix(t["project"])
            self.package[name] = project.rsplit("/", 1)[0] if "/" in project else ""
            self.bazel_name[name] = self._name_for(name, t)
        self.workspace = Workspace(workspace_root,
                                   set(self.package.values()) | {PLATFORM_PACKAGE})
        self.summary: Dict[str, dict] = {}
        # Files to copy from the reference tree: workspace path -> why.
        self.snapshots: Dict[str, str] = {}
        # The copies an earlier run made, which are in the workspace by now.
        self.copied_before: Set[str] = set()
        try:
            with open(os.path.join(workspace_root, SUMMARY), encoding="utf-8") as f:
                self.copied_before = set(json.load(f).get("snapshots", {}))
        except (OSError, ValueError):
            pass
        # NuGet: package directory (lower case, with trailing backslash) -> key,
        # and which version of a package each target uses.
        self.nuget_roots: List[Tuple[str, str]] = []
        self.nuget_key: Dict[Tuple[str, str], str] = {}
        for external in report.get("externals", []):
            if external.get("kind") != "nuget" or not external.get("version"):
                continue
            key = "%s/%s" % (external["id"].lower(), external["version"])
            self.nuget_roots.append((_win(external["root"]).rstrip("\\").lower() + "\\", key))
            for consumer in external.get("consumers", []):
                self.nuget_key[(consumer, external["id"].lower())] = key
        self.winmd_owner = self._winmd_index()
        self.platform_tool: Optional[str] = None

    # ---- names --------------------------------------------------------------

    def _name_for(self, name: str, entry: dict) -> str:
        """The Bazel target is named after the file it writes for a binary (so
        the DLL another program loads by name has that name), after the project
        for a static library."""
        output = _posix(entry.get("output", "")).rsplit("/", 1)[-1]
        kind = entry.get("kind")
        if kind == "shared_library" and output:
            return _sanitize(output)
        if kind == "executable" and output:
            return _sanitize(output[:-4] if output.lower().endswith(".exe") else output)
        return _sanitize(name)

    def stem(self, name: str) -> str:
        """Base name for the helper targets of `name` (`<stem>_res`, ...)."""
        target = self.bazel_name[name]
        return target[:-4] if target.lower().endswith(".dll") else target

    def label_of(self, name: str, from_package: str, suffix: str = "") -> str:
        package = self.package[name]
        target = self.stem(name) + suffix if suffix else self.bazel_name[name]
        return ":" + target if package == from_package else "//%s:%s" % (package, target)

    def _winmd_index(self) -> Dict[str, str]:
        """`.winmd` path (repo-relative, lower case) -> the target whose MIDL
        writes it, including the copies the build makes."""
        index: Dict[str, str] = {}
        for name, t in self.targets.items():
            winrt = t.get("winrt")
            if winrt and winrt.get("winmd"):
                for path in [winrt["winmd"]] + winrt.get("copies", []):
                    index[_posix(path).lower()] = name
        return index

    # ---- paths of the reference build --------------------------------------

    def _repo_relative(self, absolute: str) -> Optional[str]:
        """Repo-relative POSIX path of an absolute path of the reference tree."""
        path = _win(absolute)
        if self.reference_root and path.lower().startswith(self.reference_root.lower() + "\\"):
            return _posix(os.path.normpath(path[len(self.reference_root) + 1:]))
        return None

    def _nuget_label(self, absolute: str) -> Optional[str]:
        low = _win(absolute).lower()
        for root, key in self.nuget_roots:
            if low.startswith(root):
                return "@%s//%s:%s" % (self.nuget_repo, key, _posix(_win(absolute)[len(root):]))
        return None

    def _file_label(self, path: str, package: str, why: str, unhandled: List[str]) -> Optional[str]:
        """Label of a repo-relative file a rule takes as input. A file that is
        not in the workspace was written by a build step: a rule named in
        --generated-map provides it, or it is copied from the reference tree."""
        path = _posix(path)
        if re.match(r"^[A-Za-z]:/", path):
            label = self._nuget_label(path)
            if label is None:
                unhandled.append("%s is outside the repository and in no package (%s)" % (path, why))
            return label
        hook = self._hook(path)
        if hook is not None and hook.get("file"):
            return hook["file"]
        if path in self.copied_before or not self.file_exists(
                os.path.join(self.root, path.replace("/", os.sep))):
            if not self.reference_root:
                unhandled.append("%s is generated (%s): pass --reference-root to copy it, or "
                                 "name its rule in --generated-map" % (path, why))
                return None
            self.snapshots.setdefault(path, why)
        return self.workspace.label(path, package)

    def _hook(self, path: str) -> Optional[dict]:
        low = "/" + _posix(path).lower()
        return next((h for h in self.hooks if h["match"].lower() in low), None)

    # ---- C++/WinRT ----------------------------------------------------------

    def _cppwinrt_steps(self, entry: dict) -> Dict[str, dict]:
        """The project's cppwinrt runs, by kind (`plat`, `ref`, `comp`): the
        options of each response file, split into inputs, references, the output
        directory (repo-relative) and the rest."""
        ran = set()
        for step in entry.get("steps", []):
            if step.get("kind") == "exec":
                m = re.search(r"cppwinrt_(plat|ref|comp)\.rsp", step.get("command", ""))
                if m:
                    ran.add(m.group(1))
        project_dir = _posix(entry["project"]).rsplit("/", 1)[0] if "/" in entry["project"] else ""
        out: Dict[str, dict] = {}
        for step in entry.get("steps", []):
            if step.get("kind") != "write":
                continue
            m = re.search(r"cppwinrt_(plat|ref|comp)\.rsp$", step.get("file", ""))
            if not m or m.group(1) not in ran:
                continue
            run = {"in": [], "ref": [], "out": "", "opts": []}
            tokens = _tokens(step.get("lines", []))
            i = 0
            while i < len(tokens):
                tok = tokens[i]
                value = tokens[i + 1] if tok in _CPPWINRT_VALUED and i + 1 < len(tokens) else None
                if tok in ("-in", "-input"):
                    run["in"].append(value)
                elif tok in ("-ref", "-reference"):
                    run["ref"].append(value)
                elif tok in ("-out", "-output"):
                    directory = _posix(value).rstrip("/.")
                    run["out"] = _posix(os.path.normpath(
                        directory if re.match(r"^[A-Za-z]:", directory)
                        else os.path.join(project_dir, directory)))
                elif tok in ("-comp", "-component"):
                    pass
                elif value is not None:
                    run["opts"] += [tok, value]
                else:
                    run["opts"].append(tok)
                i += 2 if value is not None else 1
            out[m.group(1)] = run
        return out

    def _winmd_labels(self, paths: Sequence[str], name: str, package: str,
                      unhandled: List[str]) -> List[str]:
        """Labels for the metadata files a cppwinrt run names. The Windows SDK's
        contracts are one label however many of them the run lists."""
        labels: List[str] = []
        for path in paths:
            low = _win(path).lower()
            if "\\windows kits\\" in low:
                label = SDK_CONTRACTS
            else:
                label = self._nuget_label(path)
                if label is None:
                    relative = self._repo_relative(path)
                    owner = self.winmd_owner.get((relative or "").lower())
                    if owner:
                        label = self.label_of(owner, package, "_winmd") if owner != name \
                            else ":" + self._winmd_name(owner)
                    else:
                        unhandled.append("metadata file %s: no package and no project of this "
                                         "build provides it" % path)
                        continue
            if label not in labels:
                labels.append(label)
        return labels

    def _winmd_name(self, name: str) -> str:
        return self.stem(name) + "_winmd"

    def _cppwinrt_tool(self, name: str) -> Optional[str]:
        key = self.nuget_key.get((name, "microsoft.windows.cppwinrt"))
        return "@%s//%s:bin/cppwinrt.exe" % (self.nuget_repo, key) if key else None

    # ---- one target ---------------------------------------------------------

    def render(self, name: str) -> Tuple[Optional[str], dict]:
        entry = self.targets[name]
        package = self.package[name]
        target = self.bazel_name[name]
        stem = self.stem(name)
        kind = entry.get("kind")
        unhandled: List[str] = []
        notes: List[str] = []
        helpers: List[str] = []
        loads: Dict[str, Set[str]] = {}
        variants = entry.get("compile", {}).get("variants", [])
        if not variants:
            return None, {"unhandled": ["no compile command line was recovered for this project"]}
        if kind not in ("static_library", "shared_library", "executable"):
            return None, {"unhandled": ["target kind %r" % kind]}

        compile_deps: List[str] = []
        generated_dirs: Set[str] = set()
        generated_headers: List[str] = []

        # C++/WinRT projections the project's build generated for itself.
        runs = self._cppwinrt_steps(entry)
        tool = self._cppwinrt_tool(name)
        if runs and not tool:
            unhandled.append("the project runs cppwinrt, but no Microsoft.Windows.CppWinRT "
                             "package is recorded for it")
        if "plat" in runs:
            foreign = [p for p in runs["plat"]["in"] if "\\windows kits\\" not in _win(p).lower()]
            if foreign:
                unhandled.append("platform projection of metadata outside the Windows SDK: %s"
                                 % foreign[0])
            generated_dirs.add(runs["plat"]["out"].lower())
            compile_deps.append(PLATFORM)
            self.platform_tool = self.platform_tool or tool
        if "ref" in runs and runs["ref"]["in"]:
            generated_dirs.add(runs["ref"]["out"].lower())
            loads.setdefault("//bazel:cppwinrt.bzl", set()).add("cppwinrt_projection")
            helpers.append("\n".join(
                ["# `%s.vcxproj.cppwinrt_ref.rsp`: the projection of the metadata the project"
                 % _posix(entry["project"]).rsplit("/", 1)[-1][:-len(".vcxproj")],
                 "# references (NuGet packages, other projects).",
                 "cppwinrt_projection(", '    name = "%s_winrt_refs",' % stem,
                 '    cppwinrt = "%s",' % tool]
                + _attr("references", self._winmd_labels(runs["ref"]["ref"], name, package, unhandled))
                + _attr("winmds", self._winmd_labels(runs["ref"]["in"], name, package, unhandled))
                + [")"]))
            compile_deps.append(":%s_winrt_refs" % stem)
        winrt = entry.get("winrt")
        module_source = None
        if winrt and winrt.get("idl"):
            namespace = _posix(winrt["winmd"]).rsplit("/", 1)[-1][:-len(".winmd")]
            loads.setdefault("//bazel:winrt.bzl", set()).add("winrt_winmd")
            references = []
            for ref in winrt.get("references", []):
                owner = self.winmd_owner.get(_posix(ref).lower())
                if owner and owner != name:
                    references.append(self.label_of(owner, package, "_winmd"))
            helpers.append("\n".join(
                ["# The component's metadata: `midl /winrt` + `mdmerge` of its MIDL 3.",
                 "winrt_winmd(", '    name = "%s",' % self._winmd_name(name)]
                + _attr("srcs", [self.workspace.label(i, package) for i in winrt["idl"]])
                + ['    mdmerge = "@windows_sdk//:bin/x64/mdmerge.exe",',
                   '    midl = "@windows_sdk//:bin/x64/midl.exe",',
                   '    namespace = "%s",' % namespace]
                + _attr("opts", winrt.get("midl_options", []))
                + _attr("references", sorted(references))
                + ['    sdk_winmds = ["@windows_sdk//:winmds"],', ")"]))
            comp = runs.get("comp")
            if comp and comp["in"]:
                generated_dirs.add(comp["out"].lower())
                loads.setdefault("//bazel:cppwinrt.bzl", set()).add("cppwinrt_component")
                helpers.append("\n".join(
                    ["# `cppwinrt -component`: `<Class>.g.h`, `<Class>.g.cpp` and the module's",
                     "# activation factories.",
                     "cppwinrt_component(", '    name = "%s_component",' % stem,
                     '    cppwinrt = "%s",' % tool]
                    + _attr("opts", comp["opts"])
                    + _attr("references", self._winmd_labels(comp["ref"], name, package, unhandled))
                    + _attr("winmds", [":" + self._winmd_name(name)])
                    + [")", "", "filegroup(", '    name = "%s_module",' % stem,
                       '    srcs = [":%s_component"],' % stem,
                       '    output_group = "module",', ")"]))
                compile_deps.append(":%s_component" % stem)
                module_source = (comp["out"] + "/module.g.cpp").lower()
            else:
                unhandled.append("the project has WinRT interface definitions but no "
                                 "`cppwinrt -component` run was recorded")

        # Other generated files its compiles read.
        for generated in entry.get("generated_inputs", []):
            directory = _posix(generated["dir"])
            if directory.lower() in generated_dirs:
                continue
            if "names" not in generated:
                unhandled.append("%d generated files under %s and no rule known for them"
                                 % (generated["files"], directory))
                continue
            for relative in generated["names"]:
                path = directory + "/" + relative
                hook = self._hook(path)
                if hook is not None:
                    compile_deps += [d for d in hook.get("deps", []) if d not in compile_deps]
                    continue
                label = self._file_label(path, package, "read by the compiles of %s" % name,
                                         unhandled)
                if label:
                    generated_headers.append(label)

        # What it reads from packages.
        external_reads = entry.get("external_reads", {})
        for token, read in sorted(external_reads.items()):
            if token.startswith("@vcpkg"):
                for port in read.get("ports", []):
                    compile_deps.append("@%s//:%s" % (self.vcpkg_repo, port))
                if not read.get("ports"):
                    unhandled.append("%d files read from %s, of no port vcpkg's database lists"
                                     % (read["files"], token))
            elif token.startswith("@nuget/"):
                key = self.nuget_key.get((name, token[len("@nuget/"):]))
                if key:
                    compile_deps.append("@%s//%s:cc.headers" % (self.nuget_repo, key))
                else:
                    unhandled.append("headers read from %s, which is not recorded for this target"
                                     % token)

        present = [h for h in entry.get("headers", [])
                   if self.file_exists(os.path.join(self.root, h.replace("/", os.sep)))]
        headers = [self.workspace.label(h, package) for h in present
                   if not h.lower().endswith(_SOURCE_EXTENSIONS)]
        # A file with a source extension that a compile INCLUDES. Listed in
        # `srcs` it would be compiled on its own; rules_cc has `textual_hdrs`
        # for it, on libraries only.
        textual = [self.workspace.label(h, package) for h in present
                   if h.lower().endswith(_SOURCE_EXTENSIONS)]
        if textual:
            loads.setdefault("@rules_cc//cc:defs.bzl", set()).add("cc_library")
            helpers.append("\n".join(
                ["# Sources the project includes rather than compiles.",
                 "cc_library(", '    name = "%s.included",' % stem]
                + _attr("textual_hdrs", textual) + [")"]))
            compile_deps.append(":%s.included" % stem)
        missing = [h for h in entry.get("headers", [])
                   if not self.file_exists(os.path.join(self.root, h.replace("/", os.sep)))]
        for header in missing:
            unhandled.append("header %s was read by the reference build and is not in the "
                             "workspace" % header)

        # Directories of the INCLUDE variable that are the repository's: searched
        # after the command line's, and only on the reference side unless stated.
        # (A package's directory there is a dependency already.)
        environment = [e for e in entry.get("include_environment", [])
                       if not e.startswith("@") and not re.match(r"^[A-Za-z]:", e)
                       and self._below_a_project(e)]

        # Compiles: the first variant is the target, each other one a library
        # of its own (rules_cc has one set of options per target).
        compiled: List[str] = []
        features: Set[str] = {_CRT[f] for v in variants for f in v["flags"] if _CRT.get(f)}
        extra_libraries: List[str] = []
        pch = entry.get("precompiled_header") or {}
        pch_source = _posix(pch.get("created_by") or "").lower()
        pch_unused = {_posix(p).lower() for p in pch.get("not_using", [])}
        for index, variant in enumerate(variants):
            srcs: List[str] = []
            # reference path (lower case) of each source, by label
            path_of: Dict[str, str] = {}
            for source in variant["sources"]:
                if module_source and _posix(source).lower() == module_source:
                    srcs.append(":%s_module" % stem)
                    continue
                label = self._file_label(source, package, "compiled by %s" % name, unhandled)
                if label:
                    srcs.append(label)
                    path_of[label] = _posix(source).lower()
            copts: List[str] = []
            for include in variant["includes"] + environment:
                include = _posix(include)
                # A package's directory comes with a dependency: the port or
                # package whose headers were read, and for a directory nothing
                # was read from, a target that is the search path alone.
                if include.startswith("@vcpkg"):
                    compile_deps.append("@%s//:include" % self.vcpkg_repo)
                elif include.startswith("@nuget/"):
                    key = self.nuget_key.get((name, include[len("@nuget/"):].split("/", 1)[0]))
                    if key and self.lock.get("packages", {}).get(key, {}).get("cc", {}).get("include_dirs"):
                        compile_deps.append("@%s//%s:cc.headers" % (self.nuget_repo, key))
                if include.startswith("@") or include.lower() in generated_dirs:
                    continue          # a dependency provides it
                if "/I" + include not in copts:
                    copts.append("/I" + include)
            for flag in sorted(variant["flags"], key=_option_order):
                if flag not in _CRT:
                    copts.append(flag)
            copts += [f for f in entry.get("external_headers", {}).get("flags", [])
                      if f not in copts]
            copts += [f for f in entry.get("optimization", {}).get("compile", [])
                      if f not in copts]
            read = headers + generated_headers
            body = (_attr("srcs", srcs + read)
                    + _attr("copts", copts)
                    + _attr("local_defines", variant["defines"]))
            creator = next((l for l in srcs if path_of.get(l) == pch_source), None) \
                if index == 0 and pch_source and pch.get("header") else None
            if creator:
                # The project's precompiled header: built once (`/Yc`), used by
                # every source of the project that does not opt out (`/Yu`).
                loads.setdefault("//bazel:pch.bzl", set()).add("msvc_precompiled_header")
                helpers.append("\n".join(
                    ["# `/Yc\"%s\"`: the project's precompiled header." % pch["header"],
                     "msvc_precompiled_header(", '    name = "%s_pch",' % stem,
                     '    src = "%s",' % creator, '    header = "%s",' % pch["header"]]
                    + _attr("hdrs", read) + _attr("copts", copts)
                    + _attr("features", sorted(features))
                    + _attr("local_defines", variant["defines"])
                    + _attr("deps", sorted(set(compile_deps)))
                    + (["    alwayslink = True,"] if kind != "static_library" else []) + [")"]))
                plain = [l for l in srcs if path_of.get(l) in pch_unused]
                using = [l for l in srcs if l != creator and l not in plain]
                if plain:
                    loads.setdefault("@rules_cc//cc:defs.bzl", set()).add("cc_library")
                    extra_libraries.append(":%s.nopch" % stem)
                    helpers.append("\n".join(
                        ["# Sources the project compiles without its precompiled header.",
                         "cc_library(", '    name = "%s.nopch",' % stem]
                        + _attr("srcs", plain + read) + _attr("copts", copts)
                        + _attr("local_defines", variant["defines"])
                        + _attr("features", sorted(features))
                        + _attr("deps", sorted(set(compile_deps)))
                        # A program's objects are all linked; a static
                        # library's are taken on demand.
                        + (["    alwayslink = True,"] if kind != "static_library" else []) + [")"]))
                compiled = (_attr("srcs", using + read)
                            + _attr("additional_compiler_inputs", [":%s_pch" % stem])
                            + _attr("copts", copts + ["/Yu" + pch["header"],
                                                      "/Fp$(execpath :%s_pch)" % stem])
                            + _attr("local_defines", variant["defines"]))
                extra_libraries.append(":%s_pch" % stem)
            elif index == 0:
                compiled = body
            else:
                loads.setdefault("@rules_cc//cc:defs.bzl", set()).add("cc_library")
                extra = "%s.variant%d" % (stem, index)
                extra_libraries.append(":" + extra)
                helpers.append("\n".join(
                    ["# Sources the project compiles with other options than the rest.",
                     "cc_library(", '    name = "%s",' % extra] + body
                    + _attr("features", sorted(features))
                    + _attr("deps", sorted(set(compile_deps)))
                    + (["    alwayslink = True,"] if kind != "static_library" else []) + [")"]))

        # Resources.
        link_deps: List[str] = []
        for index, resource in enumerate(entry.get("resources", [])):
            loads.setdefault("//bazel:rc.bzl", set()).add("windows_resources")
            res_name = "%s_res" % stem if index == 0 else "%s_res%d" % (stem, index + 1)
            script = self._file_label(resource["script"], package, "resource script of %s" % name,
                                      unhandled)
            read = [self.workspace.label(p, package) for p in resource.get("reads", [])]
            deps: List[str] = []
            for path in resource.get("generated_reads", []):
                hook = self._hook(path)
                if hook is not None:
                    deps += [d for d in hook.get("deps", []) if d not in deps]
                    continue
                label = self._file_label(path, package, "read by the resource script of %s" % name,
                                         unhandled)
                if label:
                    read.append(label)
            # rc.exe looks a file up beside the current directory, which was the
            # project directory in the reference build.
            includes = [package or "."] + [_posix(i) for i in resource.get("includes", []) + environment
                                           if not i.startswith("@")]
            helpers.append("\n".join(
                ["windows_resources(", '    name = "%s",' % res_name, '    src = "%s",' % script]
                + _attr("hdrs", sorted(set(read)))
                + _attr("defines", resource.get("defines", []))
                + _attr("includes", includes)
                + _attr("opts", resource.get("options", []))
                + ['    rc = "@windows_sdk//:bin/x64/rc.exe",']
                + _attr("deps", deps) + [")"]))
            link_deps.append(":" + res_name)

        # The link.
        linkopts: List[str] = []
        linker_inputs: List[str] = []
        def_file = None
        if kind != "static_library":
            for flag in entry.get("optimization", {}).get("link", []):
                # Incremental link-time code generation keeps state beside the
                # output, which no action declares; the code is the same.
                flag = "/LTCG" if flag.upper().startswith("/LTCG:INCREMENTAL") else flag
                if flag not in linkopts:
                    linkopts.append(flag)
        # For a static library these are the libraries its ARCHIVE step was
        # given (`<Lib><AdditionalDependencies>`): MSBuild copies their members
        # into the library, so whoever links it gets them without naming them.
        # A cc_library cannot contain another library; it hands them on as
        # dependencies and link options, which reach the same links.
        for dep in entry.get("deps", []):
            if not dep.get("external"):
                other = dep["name"]
                if other not in self.targets:
                    unhandled.append("links %s, which is not a C++ target of this build" % other)
                elif self.targets[other].get("kind") == "shared_library":
                    link_deps.append(self.label_of(other, package, ".import"))
                else:
                    link_deps.append(self.label_of(other, package))
            elif dep.get("origin") == "nuget":
                label = self._nuget_library(name, dep["name"])
                if label:
                    link_deps.append(label)
                else:
                    unhandled.append("links %s.lib from a NuGet package the lock does not "
                                     "list a library of that name for" % dep["name"])
            elif dep.get("origin") == "vcpkg":
                notes.append("links %s.lib from vcpkg by name: reached through the port "
                             "dependencies" % dep["name"])
            elif dep.get("origin", "") in _SYSTEM_ORIGINS:
                linkopts.append(dep["name"] + ".lib")
            else:
                unhandled.append("links %s.lib of origin %s" % (dep["name"], dep.get("origin")))
        for flag in entry.get("link_flags", []):
            upper = flag.upper()
            if upper.startswith("/DEF:"):
                def_file = self._file_label(flag[len("/DEF:"):], package,
                                            "module definition file of %s" % name, unhandled)
            elif upper.startswith(_LINK_IMPLIED):
                continue
            elif upper.startswith(_LINK_MANAGED_ONLY):
                notes.append("%s dropped: it embeds a managed resource, which a native "
                             "image does not have" % flag)
            elif upper.startswith(_LINK_FILE):
                option, _, path = flag.partition(":")
                label = self._file_label(path, package, "%s of %s" % (option, name), unhandled)
                if label:
                    linker_inputs.append(label)
                    linkopts.append("%s:$(execpath %s)" % (option, label))
            else:
                linkopts.append(flag)

        loads.setdefault("@rules_cc//cc:defs.bzl", set()).add(
            "cc_library" if kind == "static_library" else "cc_binary")
        rule = ["# From %s (%s), via msbuild.report.json."
                % (_posix(entry["project"]), entry.get("configuration", "")),
                "cc_library(" if kind == "static_library" else "cc_binary(",
                '    name = "%s",' % target] + compiled
        rule += _attr("additional_linker_inputs", linker_inputs)
        rule += _attr("features", sorted(features))
        rule += _attr("linkopts", linkopts)
        if kind == "shared_library":
            rule.append("    linkshared = True,")
        rule.append('    visibility = ["//visibility:public"],')
        if def_file:
            rule.append('    win_def_file = "%s",' % def_file)
        deps = sorted(set(compile_deps)) + extra_libraries + link_deps
        rule += _attr("deps", list(dict.fromkeys(deps)))
        rule.append(")")
        if kind == "shared_library":
            loads["@rules_cc//cc:defs.bzl"].add("cc_import")
            rule += ["", "# For a project that links this DLL: its import library.",
                     "filegroup(", '    name = "%s.interface",' % stem,
                     '    srcs = [":%s"],' % target, '    output_group = "interface_library",', ")",
                     "", "cc_import(", '    name = "%s.import",' % stem,
                     '    interface_library = ":%s.interface",' % stem,
                     '    shared_library = ":%s",' % target,
                     '    visibility = ["//visibility:public"],', ")"]

        summary: dict = {"label": "//%s:%s" % (package, target), "kind": kind}
        if module_source:
            summary["generated_sources"] = {
                module_source: "bazel-out/x64_windows-opt/bin/%s%s_component.sources/module.g.cpp"
                               % (package + "/" if package else "", stem)}
        if generated_dirs:
            summary["generated_include_dirs"] = sorted(generated_dirs)
        if pch.get("header") and not any("_pch" in d for d in extra_libraries):
            notes.append("precompiled header %s not used: the source creating it is not among "
                         "the project's first group of sources" % pch.get("header"))
        if notes:
            summary["notes"] = notes
        if unhandled:
            summary["unhandled"] = unhandled
            return None, summary
        text = "\n\n".join(helpers + ["\n".join(rule)])
        summary["loads"] = {k: sorted(v) for k, v in loads.items()}
        return text, summary

    def _below_a_project(self, directory: str) -> bool:
        """Whether a repo-relative directory is inside some project's directory
        (and not, say, a folder of restored packages at the root)."""
        low = _posix(directory).lower() + "/"
        return any(p and low.startswith(p.lower() + "/") for p in self.package.values())

    def _nuget_library(self, name: str, library: str) -> Optional[str]:
        """Label of the library `library` (as the link names it, lower case, no
        extension) in a NuGet package this target uses."""
        for (consumer, package_id), key in sorted(self.nuget_key.items()):
            if consumer != name:
                continue
            for lib in self.lock.get("packages", {}).get(key, {}).get("cc", {}).get("libs", []):
                file_name = lib.rsplit("/", 1)[-1]
                if file_name.lower() in (library.lower() + ".lib", library.lower()):
                    return "@%s//%s:cc.%s" % (self.nuget_repo, key, file_name)
        return None

    # ---- everything ---------------------------------------------------------

    def emit(self) -> Dict[str, str]:
        """BUILD file path (workspace-relative) -> content."""
        by_package: Dict[str, List[Tuple[str, str]]] = {}
        loads_of: Dict[str, Dict[str, Set[str]]] = {}
        for name in sorted(self.targets):
            if self.only and name not in self.only:
                continue
            text, summary = self.render(name)
            loads = summary.pop("loads", {})
            self.summary[name] = summary
            if text is None:
                continue
            package = self.package[name]
            by_package.setdefault(package, []).append((name, text))
            for bzl, symbols in loads.items():
                loads_of.setdefault(package, {}).setdefault(bzl, set()).update(symbols)
        files: Dict[str, str] = {}
        for package, rendered in by_package.items():
            lines = [MARKER + ".", ""]
            for bzl in sorted(loads_of.get(package, {})):
                lines.append('load("%s", %s)' % (bzl, ", ".join(
                    '"%s"' % s for s in sorted(loads_of[package][bzl]))))
            lines.append("")
            lines.append("\n\n".join(text for _, text in rendered))
            files[(package + "/" if package else "") + "BUILD.bazel"] = "\n".join(lines) + "\n"
        if self.platform_tool:
            files[PLATFORM_PACKAGE + "/BUILD.bazel"] = "\n".join([
                MARKER + ".", "",
                'load("//bazel:cppwinrt.bzl", "cppwinrt_projection")', "",
                "# The C++/WinRT projection of the Windows SDK. MSBuild regenerates it into",
                "# every project's `<IntDir>Generated Files`; here it is built once.",
                "cppwinrt_projection(", '    name = "platform",',
                '    cppwinrt = "%s",' % self.platform_tool,
                '    visibility = ["//visibility:public"],',
                '    winmds = ["%s"],' % SDK_CONTRACTS, ")"]) + "\n"
        return files


def config_suggestions(emitter: "Emitter") -> dict:
    """What `any2bazel.json` needs so that the differ pairs the two builds:
    programs and DLLs are named after their files here and after their
    projects in the reference; packages and generated headers are in other
    places."""
    report = emitter.report
    target_map: Dict[str, str] = {}
    include_map: List[dict] = []
    source_map: List[dict] = []
    out = "bazel-out/x64_windows-opt/bin/"

    def include(prefix: str, token: str) -> None:
        for spelled in (prefix, out + prefix):
            if {"from": spelled, "to": token} not in include_map:
                include_map.append({"from": spelled, "to": token})

    for name, record in sorted(emitter.summary.items()):
        if "unhandled" in record or "label" not in record:
            continue
        label = record["label"][2:]
        if record.get("kind") != "static_library" and label.rsplit(":", 1)[-1] != name:
            target_map[name] = label
        for directory in record.pop("generated_include_dirs", []):
            # Reference: one directory per project with every projection in it.
            include_map.append({"from": directory, "to": "@cppwinrt"})
            cased = next((g["dir"] for g in report["targets"][name].get("generated_inputs", [])
                          if g["dir"].lower() == directory), None)
            if cased and cased != directory:
                include_map.append({"from": cased, "to": "@cppwinrt"})
        package = label.rsplit(":", 1)[0]
        stem = emitter.stem(name)
        for suffix in ("_component", "_winrt_refs"):
            include_map.append({"from": "%s%s/%s%s" % (out, package, stem, suffix), "to": "@cppwinrt"})
        for reference, built in record.pop("generated_sources", {}).items():
            token = "@cppwinrt/%s/module.g.cpp" % name
            cased = next((s for v in report["targets"][name]["compile"]["variants"]
                          for s in v["sources"] if s.lower() == reference), reference)
            source_map += [{"from": cased, "to": token}, {"from": built, "to": token}]
    include_map.append({"from": out + PLATFORM_PACKAGE + "/platform", "to": "@cppwinrt"})
    # A source a package has its consumers compile: the model of the reference
    # build spells it with the package's token, so only the place Bazel has
    # the package in needs a rule.
    compiled_from = {key for name, record in emitter.summary.items() if "label" in record
                     for variant in report["targets"][name].get("compile", {}).get("variants", [])
                     for source in variant.get("sources", [])
                     for root, key in emitter.nuget_roots
                     if _win(source).lower().startswith(root)}
    source_dir_map: List[dict] = []
    for _, key in emitter.nuget_roots:
        token = "@nuget/" + key.split("/", 1)[0]
        external = "external/+nuget_assets+%s/%s" % (emitter.nuget_repo, key)
        include(external, token)
        if key in compiled_from and {"from": external, "to": token} not in source_dir_map:
            source_dir_map.append({"from": external, "to": token})
    include("external/+vcpkg_install+%s/installed" % emitter.vcpkg_repo, "@vcpkg")
    ignore: dict = {"include_map": include_map, "source_map": source_map,
                    "source_dir_map": source_dir_map}
    if any("ASSEMBLYRESOURCE" in note for record in emitter.summary.values()
           for note in record.get("notes", [])):
        # Dropped by the emitter, with a note on the target: it embeds a
        # managed resource, which a native image does not have.
        ignore["link_flags_prefixes"] = ["/ASSEMBLYRESOURCE:"]
    return {"target_map": target_map, "ignore": ignore}


def write(files: Dict[str, str], exports: Dict[str, Set[str]], snapshots: Dict[str, str],
          root: str, reference_root: str) -> List[str]:
    """Write `files`, copy `snapshots` from the reference tree, and put export
    blocks into the BUILD files of packages other packages take files from.
    Returns what was skipped (not ours to overwrite)."""
    skipped: List[str] = []
    for relative, content in sorted(files.items()):
        path = os.path.join(root, relative.replace("/", os.sep))
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                existing = f.read()
            if not existing.startswith(MARKER):
                skipped.append(relative)
                continue
            content += foreign_export_blocks(existing, EXPORTS_BEGIN)
        os.makedirs(os.path.dirname(path) or root, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    for relative in sorted(snapshots):
        source = os.path.join(reference_root, relative.replace("/", os.sep))
        destination = os.path.join(root, relative.replace("/", os.sep))
        os.makedirs(os.path.dirname(destination), exist_ok=True)
        shutil.copyfile(source, destination)
    for package, names in sorted(exports.items()):
        path = os.path.join(root, package.replace("/", os.sep), "BUILD.bazel")
        block = "\n".join([EXPORTS_BEGIN, "exports_files(%s)" % _fmt_list(sorted(names), 4),
                           EXPORTS_END]) + "\n"
        existing = ""
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                existing = f.read()
        if EXPORTS_BEGIN in existing:
            head, _, rest = existing.partition(EXPORTS_BEGIN)
            _, _, tail = rest.partition(EXPORTS_END)
            existing = head + block + tail.lstrip("\n")
        else:
            existing = existing + ("\n" if existing and not existing.endswith("\n\n") else "") + block
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(existing)
    return skipped


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("report")
    parser.add_argument("lock")
    parser.add_argument("workspace", help="root of the Bazel workspace to write into")
    parser.add_argument("--reference-root", help="tree the reference build ran in (to resolve "
                        "the paths it recorded and to copy generated files from)")
    parser.add_argument("--nuget-repo", default="nuget")
    parser.add_argument("--vcpkg-repo", default="vcpkg")
    parser.add_argument("--only", nargs="*", help="reference target names to emit")
    parser.add_argument("--generated-map", help="JSON list of rules for files a project-specific "
                        "build step generates: {match, deps, file}")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    with open(args.report, encoding="utf-8") as f:
        report = json.load(f)
    with open(args.lock, encoding="utf-8") as f:
        lock = json.load(f)
    hooks = []
    if args.generated_map:
        with open(args.generated_map, encoding="utf-8") as f:
            hooks = json.load(f)
    emitter = Emitter(report, lock, args.workspace, args.reference_root, args.nuget_repo,
                      args.vcpkg_repo, args.only, hooks)
    files = emitter.emit()
    skipped: List[str] = []
    if not args.dry_run:
        skipped = write(files, emitter.workspace.exports, emitter.snapshots, args.workspace,
                        args.reference_root or "")
        suggestions = config_suggestions(emitter)
        with open(os.path.join(args.workspace, SUMMARY), "w", encoding="utf-8",
                  newline="\n") as f:
            json.dump({"targets": emitter.summary, "snapshots": emitter.snapshots}, f, indent=1,
                      sort_keys=True)
            f.write("\n")
        with open(os.path.join(args.workspace, "emit_cc.any2bazel.json"), "w", encoding="utf-8",
                  newline="\n") as f:
            json.dump(suggestions, f, indent=1, sort_keys=True)
            f.write("\n")
    done = [n for n, s in emitter.summary.items() if "unhandled" not in s]
    blocked = {n: s["unhandled"] for n, s in emitter.summary.items() if "unhandled" in s}
    print("emitted %d C++ target(s) in %d BUILD file(s); %d not emitted; %d generated file(s) "
          "copied from the reference tree"
          % (len(done), len(files), len(blocked), len(emitter.snapshots)))
    for name, reasons in sorted(blocked.items()):
        print("  %s: %s%s" % (name, reasons[0],
                              " (+%d more)" % (len(reasons) - 1) if len(reasons) > 1 else ""))
    for relative, why in sorted(emitter.snapshots.items()):
        print("  snapshot  %s (%s)" % (relative, why))
    for relative in skipped:
        print("  not overwritten (no marker): %s" % relative)
    return 0


if __name__ == "__main__":
    sys.exit(main())
