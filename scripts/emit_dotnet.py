"""Write rules_dotnet BUILD files for the C# targets of an MSBuild build.

    python3 emit_dotnet.py <msbuild.report.json> <nuget_lock.json> <workspace> \\
        [--reference-root DIR] [--nuget-repo nuget] [--only NAME ...] [--dry-run]
        [--generated-map FILE]

A C# project is far more uniform than a C++ one: its compile is one command
line, and the report's `csharp` digest already says where every input of that
command line comes from. This script restates each digest as a
`csharp_library` / `csharp_binary` / `csharp_test`, or, where rules_dotnet's own
rules cannot reproduce the compile (`msbuild_csharp.rules_dotnet_gaps`), as an
`exact_csharp_assembly` of the `csc_assembly.bzl` template:

  * sources listed explicitly (MSBuild's default is a glob; the build's actual
    list is what the diff compares);
  * every compiler option as the attribute rules_dotnet has for it, or in
    `compiler_options` when it has none;
  * NuGet packages as the lock's per-framework targets, other projects as
    labels, and the files MSBuild generates for every SDK-style project
    (assembly info, the target-framework attribute, the `build_property.*`
    analyzer config) as `write_file` targets with the reference's content.

It is a starting point, not an authority: run the diff on the result, and
`check_generated.py` after building it. What it cannot express is listed per
target under `unhandled` in the summary it prints (and writes to
`emit_dotnet.summary.json`), and a target with anything unhandled is not
written at all -- a BUILD file that silently drops an input would look
converged on everything else. A project that compiles XAML is `excluded`
instead: out of scope by decision, and counted apart.

`--generated-map FILE` names the rules that produce a project's own generated
sources (JSON list of {match, srcs, load, starlark, bazel_output}; see
docs/REFERENCE-msbuild-csharp.md).

Only files carrying its marker line are overwritten.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

from msbuild_csharp import classify_external, rules_dotnet_gaps

MARKER = "# Generated by any2bazel emit_dotnet.py"
EXPORTS_BEGIN = "# any2bazel:dotnet-exports begin (generated; do not edit between the markers)"
EXPORTS_END = "# any2bazel:dotnet-exports end"
_SKIP_DIRS = {".git", "obj", "bin", "node_modules", "packages", "vcpkg_installed", "x64", "ARM64"}

# What rules_dotnet puts on every csc command line by itself (0.22.x).
_ALREADY_DEFAULT = {"/deterministic", "/nostdlib", "/highentropyva"}
# Build-type defines both sides add on their own.
_BUILD_TYPE_DEFINES = {"TRACE", "DEBUG", "RELEASE"}
# Framework packs a rules_dotnet target gets from rules_dotnet itself. (It also
# has the .NET Framework and ASP.NET packs, but passes more of them than MSBuild
# does: targets on those are compiled by csc_assembly, from the lock.)
_FRAMEWORK_PACKS_PROVIDED = ("microsoft.netcore.app.ref", "netstandard.library")
# `NET8_0_OR_GREATER`, `NETCOREAPP`, `WINDOWS10_0_19041_0_OR_GREATER`, ...
_FRAMEWORK_DEFINE = re.compile(r"^(NET|NETCOREAPP|NETSTANDARD|NETFRAMEWORK|WINDOWS)(\d|_|$)")
# <data ... type="System.Resources.ResXFileRef, ..."> <value>path;type</value>
_RESX_FILE_REF = re.compile(
    r'<data\b[^>]*\btype="System\.Resources\.ResXFileRef[^"]*"[^>]*>\s*<value>([^<]*)</value>',
    re.IGNORECASE | re.DOTALL)
# An absolute Windows path inside a line of text, up to a list separator.
_ABSOLUTE_PATH = re.compile(r"[A-Za-z]:[\\/][^|;,\"<>*?\r\n]+")
# Name, in a Bazel model, of the .resx converter resx.bzl builds.
RESX_TOOL = "bazel/dotnet/resx:resx2resources"
# csc options whose value is a file: an attribute of csc_assembly, or nothing.
_EXACT_FILE_OPTIONS = {"/keyfile": "keyfile", "/win32icon": "win32_icon",
                       "/win32manifest": "win32_manifest"}
_PATH_OPTIONS = {"keyfile", "win32manifest", "win32icon", "win32res", "appconfig", "ruleset"}
_BOILERPLATE = {"assembly_info", "target_framework_attribute", "global_usings",
                "test_entry_point"}


_RSP_TOKEN = re.compile(r'"([^"]*)"|(\S+)')


def _first_token(command: str) -> str:
    m = _RSP_TOKEN.match(command.strip())
    return (m.group(1) or m.group(2)) if m else ""


def _relative_to(path: str, root: str) -> str:
    """`path` below `root` (both as the reference build wrote them), POSIX."""
    p, r = _posix(path).rstrip("/"), _posix(root).rstrip("/")
    if r and p.lower().startswith(r.lower() + "/"):
        return p[len(r) + 1:]
    return p


def base_tfm(tfm: str) -> str:
    """`net8.0-windows10.0.26100.0` -> `net8.0`: rules_dotnet has no platform
    frameworks. What the platform adds (defines, the Windows SDK projection
    assemblies) is stated explicitly on the target instead."""
    return tfm.split("-", 1)[0].lower()


def _posix(path: str) -> str:
    return path.replace("\\", "/")


def _sanitize(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.+\-]", "_", name)


def _fmt_list(items: Iterable[str], indent: int = 8) -> str:
    items = list(items)
    if not items:
        return "[]"
    pad = " " * indent
    return "[\n" + "".join('%s"%s",\n' % (pad, i.replace("\\", "\\\\").replace('"', '\\"'))
                           for i in items) + " " * (indent - 4) + "]"


def _is_intermediate(path: str) -> bool:
    """A path inside a project's intermediate directory (`obj/`)."""
    p = "/" + _posix(path).lower()
    return "/obj/" in p


def _fmt_dict(items: Dict[str, str], indent: int = 8) -> str:
    if not items:
        return "{}"
    quote = lambda v: v.replace("\\", "\\\\").replace('"', '\\"')
    pad = " " * indent
    return "{\n" + "".join('%s"%s": "%s",\n' % (pad, quote(k), quote(v))
                           for k, v in sorted(items.items())) + " " * (indent - 4) + "}"


class Workspace:
    """Package boundaries of the output tree: existing BUILD files plus the
    ones this run writes."""

    def __init__(self, root: str, new_packages: Iterable[str]):
        self.root = root
        self.packages: Set[str] = {""}
        for directory, dirs, files in os.walk(root):
            dirs[:] = [d for d in dirs if d not in _SKIP_DIRS and not d.startswith("bazel-")]
            if "BUILD.bazel" in files or "BUILD" in files:
                self.packages.add(_posix(os.path.relpath(directory, root)).strip("."))
        self.packages.update(new_packages)
        self.exports: Dict[str, Set[str]] = {}

    def package_of(self, path: str) -> str:
        directory = _posix(path).rsplit("/", 1)[0] if "/" in path else ""
        while directory and directory not in self.packages:
            directory = directory.rsplit("/", 1)[0] if "/" in directory else ""
        return directory

    def label(self, path: str, from_package: str) -> str:
        """Label of a source-tree file, exported from its package if another
        package needs it."""
        path = _posix(path)
        package = self.package_of(path)
        relative = path[len(package) + 1:] if package else path
        if package == from_package:
            return relative
        self.exports.setdefault(package, set()).add(relative)
        return "//%s:%s" % (package, relative)


class Emitter:
    def __init__(self, report: dict, lock: dict, workspace_root: str,
                 reference_root: Optional[str] = None, nuget_repo: str = "nuget",
                 only: Optional[Sequence[str]] = None, hooks: Optional[Sequence[dict]] = None):
        self.report = report
        self.lock = lock
        self.reference_root = reference_root
        self.nuget_repo = nuget_repo
        self.targets = {n: t for n, t in report.get("targets", {}).items() if t.get("csharp")}
        self.only = set(only or [])
        # Bazel target name and package of each reference target.
        by_project: Dict[str, List[str]] = {}
        for name, t in self.targets.items():
            by_project.setdefault(t["project"], []).append(name)
        self.bazel_name: Dict[str, str] = {}
        self.package: Dict[str, str] = {}
        for project, names in by_project.items():
            directory = _posix(project).rsplit("/", 1)[0] if "/" in project else ""
            for name in names:
                digest = self.targets[name]["csharp"]
                plain = name.split("[", 1)[0]
                self.bazel_name[name] = _sanitize(
                    plain if len(names) == 1 else "%s_%s" % (plain, digest["target_framework"]))
                self.package[name] = directory
        self.workspace = Workspace(workspace_root,
                                   set(self.package.values()) | {"bazel/dotnet", "bazel/winmd"})
        self.summary: Dict[str, dict] = {}
        self.sdk_analyzers: Dict[tuple, str] = {}
        self.sdk_configs: Dict[str, str] = {}
        # package -> {helper name: Starlark}: one conversion per .resx, shared
        # by the frameworks of a multi-targeted project.
        self.resx_helpers: Dict[str, Dict[str, str]] = {}
        self.framework_defines = self._framework_defines()
        # WinRT: which reference target produces which .winmd, and the
        # metadata targets some C# target turned out to need.
        self.winmd_owner = self._winmd_index()
        self.winmd_targets: Dict[str, str] = {}
        # Project-specific generators the operator has written rules for.
        self.hooks: List[dict] = list(hooks or [])
        # (path prefix, token) pairs for any2bazel.json's ignore.source_map.
        self.source_maps: List[Tuple[str, str]] = []
        # Targets rules_dotnet's own rules cannot reproduce, and why: these are
        # compiled by the exact-command-line template (csc_assembly.bzl).
        self.gaps: Dict[str, List[str]] = {
            name: rules_dotnet_gaps(t["csharp"], self.package[name])
            for name, t in self.targets.items()}

    def _reference_label(self, name: str, from_package: str) -> str:
        """What a `csc_assembly` references to compile against target `name`."""
        label = self.label_of_target(name, from_package)
        # `<name>_csc` is the compile behind an exact_csharp_assembly.
        return label + "_csc" if self.gaps.get(name) else label

    # ---- shared facts -----------------------------------------------------

    def _framework_defines(self) -> Dict[str, List[str]]:
        """Defines every project of a target framework has: the ones MSBuild
        derives from the framework itself (`NET8_0_OR_GREATER`, `WINDOWS`, ...).
        Stated once per framework instead of on every target."""
        common: Dict[str, Set[str]] = {}
        for t in self.targets.values():
            d = t["csharp"]
            defines = {x for x in d["defines"] if _FRAMEWORK_DEFINE.match(x)}
            tfm = d["target_framework"]
            common[tfm] = common[tfm] & defines if tfm in common else defines
        return {tfm: sorted(v) for tfm, v in common.items()}

    def label_of_target(self, name: str, from_package: str) -> str:
        package, target = self.package[name], self.bazel_name[name]
        return ":" + target if package == from_package else "//%s:%s" % (package, target)

    def _read_reference(self, path: str) -> Optional[List[str]]:
        if not self.reference_root:
            return None
        try:
            with open(os.path.join(self.reference_root, path.replace("/", os.sep)),
                      encoding="utf-8-sig") as f:
                return f.read().splitlines()
        except OSError:
            return None

    # ---- one target ---------------------------------------------------------

    def render(self, name: str) -> Tuple[Optional[str], dict]:
        """(Starlark for the target and its helper targets, summary entry).
        The Starlark is None when something could not be expressed."""
        entry = self.targets[name]
        d = entry["csharp"]
        package = self.package[name]
        target = self.bazel_name[name]
        tfm = d["target_framework"]
        unhandled: List[str] = []
        notes: List[str] = []
        helpers: List[str] = []
        loads: Set[str] = set()

        extra_loads: Dict[str, Set[str]] = {}
        srcs: List[str] = [self.workspace.label(s, package) for s in d["sources"]["hand_written"]]
        # The C#/WinRT projection, when the project runs cswinrt: emitted even
        # if no source of it is compiled directly, because a project-specific
        # step may post-process it (see --generated-map).
        projection = self._cswinrt(name, package, target, unhandled)
        if projection:
            helpers.append(projection["starlark"])
            extra_loads.setdefault("//bazel/dotnet:cswinrt.bzl", set()).add("cswinrt_projection")
        applied_hooks: Set[int] = set()
        boilerplate: Dict[str, int] = {}
        for g in sorted(d["sources"].get("generated", []),
                        key=lambda g: (g["kind"], g.get("path") or g.get("dir") or "")):
            kind = g["kind"]
            where = g.get("dir") or g["path"]
            hook_index = next((i for i, h in enumerate(self.hooks)
                               if h["match"].lower() in ("/" + _posix(where) + "/").lower()), None)
            if hook_index is not None:
                hook = self.hooks[hook_index]
                if hook_index not in applied_hooks:
                    applied_hooks.add(hook_index)
                    fill = {"target": target, "package": package, "nuget": self.nuget_repo}
                    srcs += [s.format(**fill) for s in hook.get("srcs", [])]
                    if hook.get("starlark"):
                        helpers.append(hook["starlark"].format(**fill))
                    for bzl, symbols in hook.get("load", {}).items():
                        extra_loads.setdefault(bzl, set()).update(symbols)
                    if hook.get("bazel_output"):
                        directory = _posix(where) if "dir" in g else _posix(where).rsplit("/", 1)[0]
                        token = "@generated/%s/%d" % (target, hook_index)
                        self.source_maps.append((directory + "/", token))
                        self.source_maps.append((
                            "bazel-bin/%s%s" % (package + "/" if package else "",
                                                hook["bazel_output"].format(**fill)), token))
                continue
            if kind == "cswinrt_projection" and projection \
                    and _posix(where).lower() == projection["output"].lower():
                srcs.append(":" + projection["name"])
                token = "@cswinrt/" + target
                self.source_maps.append((_posix(where) + "/", token))
                self.source_maps.append(("bazel-bin/%s%s" % (package + "/" if package else "",
                                                            projection["directory"]), token))
                continue
            if kind in _BOILERPLATE and "path" in g:
                lines = self._read_reference(g["path"])
                if lines is None:
                    unhandled.append("generated source %s (%s): reference file not readable; "
                                     "pass --reference-root" % (g["path"], kind))
                    continue
                # A kind can have several files (the test platform writes its
                # entry point and the list of extensions it registers).
                boilerplate[kind] = boilerplate.get(kind, 0) + 1
                helper = "%s_%s" % (target, kind) if boilerplate[kind] == 1 \
                    else "%s_%s_%d" % (target, kind, boilerplate[kind])
                # Not a path inside an output directory the compiler rule owns.
                out = "_msbuild/%s/%s" % (target, _sanitize(_posix(g["path"]).rsplit("/", 1)[-1]))
                helpers.append(_write_file(helper, out, lines,
                                           "MSBuild writes this for every SDK-style project (%s)." % kind))
                loads.add("write_file")
                srcs.append(":" + helper)
                # Pair the two builds' copies, so that dropping one is an error.
                token = "@msbuild/%s/%s" % (target, helper[len(target) + 1:])
                self.source_maps.append((_posix(g["path"]), token))
                self.source_maps.append(("bazel-bin/%s%s" % (package + "/" if package else "", out),
                                         token))
            else:
                unhandled.append("generated sources (%s): %s" % (
                    kind, g.get("dir") or g.get("path")))
        for e in d["sources"].get("external", []):
            if e.get("kind") == "nuget":
                srcs.append("@%s//%s/%s:%s" % (self.nuget_repo, e["id"], e["version"], e["path"]))
            else:
                unhandled.append("source outside the repository: %s" % e.get("path"))

        attrs: List[Tuple[str, str]] = []
        compiler_options: List[str] = []
        nowarn, as_errors, not_as_errors = [], [], []
        treat_all = False
        seen = {"warn": False, "nullable": False, "doc": False, "unsafe": False}
        exact = bool(self.gaps.get(name))
        exact_options: List[str] = []
        compile_data: List[str] = []
        for option in d["options"]:
            key, _, value = option.partition(":")
            if exact:
                # Passed as the reference build spelled them; only what names a
                # file or an output becomes an attribute.
                if key == "/target":
                    continue
                if option == "/doc":
                    seen["doc"] = True
                elif key in _EXACT_FILE_OPTIONS:
                    label = self._option_file(value, package, target, helpers, loads, unhandled)
                    if label:
                        attrs.append((_EXACT_FILE_OPTIONS[key], '"%s"' % label))
                elif key.lstrip("/") in _PATH_OPTIONS:
                    unhandled.append("compiler option naming a file, which csc_assembly has "
                                     "no attribute for: %s" % option)
                else:
                    exact_options.append(option)
                continue
            if option in _ALREADY_DEFAULT or key == "/target":
                continue
            if key == "/langversion":
                attrs.append(("langversion", '"%s"' % value))
            elif key == "/nullable":
                attrs.append(("nullable", '"%s"' % value)); seen["nullable"] = True
            elif option == "/unsafe":
                attrs.append(("allow_unsafe_blocks", "True"))
            elif key == "/warn":
                seen["warn"] = True
                if value.isdigit() and int(value) <= 5:
                    attrs.append(("warning_level", value))
                else:
                    # The attribute stops at 5; current SDKs pass their analysis
                    # level (8, 9, 10). Stated after it, so this one wins.
                    compiler_options.append(option)
            elif key == "/nowarn":
                nowarn.append(value)
            elif option == "/warnaserror":
                treat_all = True
            elif key == "/warnaserror":
                as_errors.append(value)
            elif key == "/warnaserror-":
                not_as_errors.append(value)
            elif option == "/doc":
                seen["doc"] = True
            elif key == "/keyfile":
                attrs.append(("keyfile", '"%s"' % self.workspace.label(value, package)))
            elif key.lstrip("/") in _PATH_OPTIONS:
                # rules_dotnet has no attribute for it: the option goes to the
                # compiler as a path, and the file comes along as compile data.
                if _is_intermediate(value):
                    unhandled.append("compiler option names a file the build generates (%s); "
                                     "rules_dotnet can only be given a path" % option)
                else:
                    compiler_options.append(option)
                    compile_data.append(self.workspace.label(value, package))
            else:
                compiler_options.append(option)
        if not exact:
            if not seen["warn"]:
                attrs.append(("warning_level", "4"))      # csc's default; rules_dotnet's is 3
            if not seen["nullable"]:
                attrs.append(("nullable", '"disable"'))
        if seen["doc"] or not exact:
            attrs.append(("generate_documentation_file", "True" if seen["doc"] else "False"))
        if nowarn:
            attrs.append(("nowarn", _fmt_list(sorted(nowarn))))
        if treat_all:
            attrs.append(("treat_warnings_as_errors", "True"))
            if not_as_errors:
                attrs.append(("warnings_not_as_errors", _fmt_list(sorted(not_as_errors))))
            # rules_dotnet rejects a list of ids next to "all": state it to csc directly.
            compiler_options += ["/warnaserror+:" + w for w in sorted(as_errors)]
        else:
            if as_errors:
                attrs.append(("warnings_as_errors", _fmt_list(sorted(as_errors))))
            compiler_options += ["/warnaserror-:" + w for w in sorted(not_as_errors)]

        # rules_dotnet adds TRACE itself; csc_assembly adds only DEBUG or RELEASE.
        own_defines = sorted(set(d["defines"])
                             - ({"DEBUG", "RELEASE"} if exact else _BUILD_TYPE_DEFINES)
                             - set(self.framework_defines.get(tfm, [])))
        defines = 'MSBUILD_FRAMEWORK_DEFINES["%s"]' % tfm
        if own_defines:
            defines += " + " + _fmt_list(own_defines)
        attrs.append(("defines", defines))
        loads.add("defines")

        # `deps` are rules_dotnet dependencies (compile and run time). An exact
        # compile takes `refs` and `analyzers` as files instead, and `deps`
        # only says what must come along at run time.
        deps: List[str] = []
        refs: List[str] = []
        analyzer_files: List[str] = []
        lock_target = self.lock.get("targets", {}).get(name, {})
        pack_packages = set(lock_target.get("packs", {}).values())
        for key, variant in sorted(lock_target.get("packages", {}).items()):
            label = "@%s//%s:%s" % (self.nuget_repo, key, variant)
            if exact:
                refs.append(label + ".refs")
                analyzer_files.append(label + ".analyzers")
                if key not in pack_packages:
                    deps.append(label)
            else:
                deps.append(label)
                # References that displace an assembly of rules_dotnet's own
                # pack: one target per assembly, named like it (see the lock).
                chosen = self.lock.get("packages", {}).get(key, {}).get("frameworks", {}) \
                    .get(variant, {})
                for f in chosen.get("overrides", []):
                    deps.append("%s.as.%s" % (label, _posix(f).rsplit("/", 1)[-1].rsplit(".", 1)[0]))
        for ref in d["references"].get("projects", []):
            other_name = ref["target"]
            if other_name not in self.bazel_name:
                unhandled.append("reference to %s, which is not a C# target of this build"
                                 % other_name)
                continue
            if exact:
                refs.append(self._reference_label(other_name, package))
            deps.append(self.label_of_target(other_name, package))
        for other in d["references"].get("other", []):
            owner = self.winmd_owner.get(_posix(other).lower())
            if owner and exact:
                refs.append("//bazel/winmd:" + self._winmd_target(owner))
            elif owner:
                # .NET Framework can reference WinRT metadata directly.
                deps.append("//bazel/winmd:%s_ref" % self._winmd_target(owner))
            else:
                unhandled.append("reference to a loose file: %s" % other)
        packs_used = set(d["references"].get("packs", {})) | set(d["analyzers"].get("packs", {}))
        for pack in sorted(packs_used):
            pack_id = pack.split("/", 1)[0].lower()
            if pack in lock_target.get("packs", {}):
                # Locked as the NuGet package it is: exactly the files the
                # reference build passed, a dependency like any other.
                continue
            if exact:
                unhandled.append("framework pack %s is not in the lock; write the lock with "
                                 "nuget_assets.py of this version" % pack)
            elif not pack_id.startswith(_FRAMEWORK_PACKS_PROVIDED):
                unhandled.append("framework pack rules_dotnet does not provide and the lock "
                                 "does not have: %s" % pack)
        if d["analyzers"].get("sdk"):
            shared = "//bazel/dotnet:" + self._sdk_analyzers(d["analyzers"]["sdk"])
            if exact:
                analyzer_files.append(shared + "_files")
            else:
                deps.append(shared)
        for a in d["analyzers"].get("other", []) + [p["path"] for p in d["analyzers"].get("projects", [])]:
            unhandled.append("analyzer from a loose file or project: %s" % a)

        additional: List[str] = []
        for f in d.get("additional_files", []):
            additional.append(self._input_label(f, package, unhandled, "additional file"))
        configs: List[str] = []
        for f in d.get("analyzer_configs", []):
            if f["kind"] == "generated":
                lines = self._read_reference(f["path"])
                if lines is None:
                    unhandled.append("generated analyzer config %s: reference file not readable"
                                     % f["path"])
                    continue
                helper = target + "_msbuild_editorconfig"
                comment = "The project properties MSBuild hands to analyzers and source generators."
                lines, package_files = self._package_paths(self._relocate(lines))
                if package_files:
                    # Some properties are paths into packages, which a source
                    # generator opens: the file by label, wherever Bazel has it.
                    helpers.append("\n".join([
                        "# " + comment, "msbuild_editorconfig(", '    name = "%s",' % helper,
                        '    out = "_msbuild/%s/msbuild.editorconfig",' % target,
                        "    files = %s," % _fmt_dict(package_files),
                        "    lines = %s," % _fmt_list(list(lines) + [""]), ")"]))
                    extra_loads.setdefault("//bazel/dotnet:msbuild_config.bzl", set()).add(
                        "msbuild_editorconfig")
                    compile_data += sorted(package_files)
                else:
                    helpers.append(_write_file(helper, "_msbuild/%s/msbuild.editorconfig" % target,
                                               lines, comment))
                    loads.add("write_file")
                configs.append(":" + helper)
            elif f["kind"] == "sdk":
                configs.append("//bazel/dotnet:" + self._sdk_config(f["path"]))
            else:
                configs.append(self._input_label(f, package, unhandled, "analyzer config"))
        resources: List[str] = []
        named_resources: Dict[str, str] = {}
        for r in d.get("resources", []):
            prefix = d["assembly"] + "."
            source = r.get("from", "")
            if exact:
                # Any file under any name.
                if source.lower().endswith(".resx"):
                    helper = _sanitize(r["name"].rsplit(".", 1)[0]) + "_resx"
                    if helper not in self.resx_helpers.setdefault(package, {}):
                        self.resx_helpers[package][helper] = "\n".join([
                            "# MSBuild's GenerateResource: embedded as %s." % r["name"],
                            "resx_resources(", '    name = "%s",' % helper,
                            '    src = "%s",' % self.workspace.label(source, package),
                            '    out = "%s",' % r["name"]]
                            + self._resx_linked(source, package) + [")"])
                    loads.add("resx_resources")
                    named_resources[":" + helper] = r["name"]
                elif r["kind"] == "repo":
                    named_resources[self.workspace.label(r["path"], package)] = r["name"]
                else:
                    unhandled.append("embedded resource %s, which the build generates (%s)"
                                     % (r["name"], r["path"]))
                continue
            if not source.lower().endswith(".resx"):
                if r["kind"] == "repo" and r["name"] == self._plain_resource_name(d, r["path"], package):
                    resources.append(self.workspace.label(r["path"], package))
                else:
                    unhandled.append("embedded resource %s (from %s)" % (r["name"], r["path"]))
                continue
            if not r["name"].startswith(prefix):
                # rules_dotnet always names a resource after the assembly.
                unhandled.append("resource %s: its name does not start with the assembly name, "
                                 "which rules_dotnet's `resources` cannot express" % r["name"])
                continue
            if self.workspace.package_of(source) != package:
                unhandled.append("resource %s: %s is outside the project's package" % (r["name"], source))
                continue
            out_name = r["name"][len(prefix):]
            helper = _sanitize(out_name.rsplit(".", 1)[0]) + "_resx"
            if helper not in self.resx_helpers.setdefault(package, {}):
                self.resx_helpers[package][helper] = "\n".join([
                    "# MSBuild's GenerateResource: embedded as %s." % r["name"],
                    "resx_resources(", '    name = "%s",' % helper,
                    '    src = "%s",' % self.workspace.label(source, package),
                    '    out = "%s",' % out_name] + self._resx_linked(source, package) + [")"])
            loads.add("resx_resources")
            resources.append(":" + helper)

        summary = {"package": package, "target": target, "notes": notes}
        # A project that compiles XAML embeds the compiled markup as
        # `<assembly>.g.resources`. Out of scope by decision, not by accident:
        # reported apart from what could not be expressed.
        markup = [r["name"] for r in d.get("resources", [])
                  if r["name"].lower().endswith(".g.resources")]
        if markup:
            summary["excluded"] = "XAML: the project compiles markup (%s)" % markup[0]
        if unhandled:
            summary["unhandled"] = unhandled
            return None, summary

        if exact:
            rule = "exact_csharp_assembly"
            extra_loads.setdefault("//bazel/dotnet:csc_assembly.bzl", set()).add(rule)
            out = [helpers and "\n".join(helpers) or ""]
            out += ["# rules_dotnet's own rules cannot reproduce this compile:"]
            out += ["#   " + gap for gap in self.gaps[name]]
            out += ["%s(" % rule, '    name = "%s",' % target,
                    "    srcs = %s," % _fmt_list(sorted(set(srcs), key=str.lower)),
                    '    assembly_name = "%s",' % d["assembly"]]
            if d["target"] != "library":
                attrs.append(("kind", '"%s"' % d["target"]))
                notes.append("an executable compiled by csc_assembly: built and referenceable, "
                             "not runnable under Bazel (no host)")
            attrs.append(("deps", _fmt_list(sorted(set(deps)))))
            if named_resources:
                attrs.append(("resources", _fmt_dict(named_resources)))
            if additional:
                attrs.append(("additionalfiles", _fmt_list(sorted({a for a in additional if a}))))
            if configs:
                attrs.append(("analyzer_configs", _fmt_list(sorted({c for c in configs if c}))))
            if exact_options:
                attrs.append(("options", _fmt_list(sorted(exact_options))))
            if compile_data:
                attrs.append(("compile_data", _fmt_list(sorted(set(compile_data)))))
            attrs.append(("refs", _fmt_list(sorted(set(refs)))))
            attrs.append(("analyzers", _fmt_list(sorted(set(analyzer_files)))))
            attrs.append(("target_framework", '"%s"' % base_tfm(tfm)))
            attrs.append(("visibility", '["//visibility:public"]'))
            out += ["    %s = %s," % (k, v) for k, v in sorted(attrs)]
            out.append(")")
            summary["loads"] = sorted(loads)
            summary["extra_loads"] = {k: sorted(v) for k, v in extra_loads.items()}
            summary["rule"] = rule
            summary["exact"] = list(self.gaps[name])
            return "\n".join(x for x in out if x), summary

        # A test project that runs itself (Microsoft.Testing.Platform writes it
        # a real entry point) is a test to Bazel too. One hosted by VSTest is
        # also compiled as a program, but its generated `Main` is empty: as a
        # `csharp_test` it would pass without running anything.
        is_test = entry.get("role") == "test" or bool(entry.get("test"))
        self_running = any(g["kind"] == "test_entry_point" and
                           "platformentrypoint" in _posix(g.get("path", "")).lower()
                           for g in d["sources"].get("generated", []))
        if d["target"] == "library":
            rule = "csharp_library"
        elif is_test and self_running:
            rule = "csharp_test"
        else:
            rule = "csharp_binary"
            if is_test:
                notes.append("a VSTest-hosted test assembly: built as a program whose entry "
                             "point does nothing; running its tests needs a test host")
        loads.add(rule)
        out = [helpers and "\n".join(helpers) or "", "%s(" % rule, '    name = "%s",' % target,
               "    srcs = %s," % _fmt_list(sorted(set(srcs), key=str.lower)),
               '    out = "%s",' % d["assembly"]]
        if resources:
            attrs.append(("resources", _fmt_list(sorted(resources))))
        if additional:
            attrs.append(("additionalfiles", _fmt_list(sorted({a for a in additional if a}))))
        if configs:
            attrs.append(("analyzer_configs", _fmt_list(sorted({c for c in configs if c}))))
        if d["target"] == "winexe":
            # rules_dotnet (0.22.2) declares `winexe` and then compiles every
            # binary with /target:exe: a program for the Windows subsystem
            # would open a console. The last /target on the line wins.
            attrs.append(("winexe", "True"))
            compiler_options.append("/target:winexe")
        if compiler_options:
            attrs.append(("compiler_options", _fmt_list(sorted(compiler_options))))
        if compile_data:
            attrs.append(("compile_data", _fmt_list(sorted(set(compile_data)))))
        attrs.append(("target_frameworks", '["%s"]' % base_tfm(tfm)))
        attrs.append(("visibility", '["//visibility:public"]'))
        attrs.append(("deps", _fmt_list(sorted(set(deps)))))
        out += ["    %s = %s," % (k, v) for k, v in sorted(attrs)]
        out.append(")")
        summary["loads"] = sorted(loads)
        summary["extra_loads"] = {k: sorted(v) for k, v in extra_loads.items()}
        summary["rule"] = rule
        return "\n".join(x for x in out if x), summary

