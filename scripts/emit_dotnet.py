    def _winmd_index(self) -> Dict[str, str]:
        """`.winmd` path (repo-relative, lower-case) -> the reference target
        whose MIDL produces it, following the copies the build makes of it."""
        index: Dict[str, str] = {}
        for name, t in self.report.get("targets", {}).items():
            winrt = t.get("winrt")
            if winrt and winrt.get("winmd"):
                for path in [winrt["winmd"]] + winrt.get("copies", []):
                    index[_posix(path).lower()] = name
        changed = True
        while changed:
            changed = False
            for t in self.report.get("targets", {}).values():
                for step in t.get("steps", []):
                    if step.get("kind") != "copy" or isinstance(step.get("to"), str):
                        continue
                    for source, destination in zip(step.get("from", []), step.get("to", [])):
                        owner = index.get(_posix(source).lower())
                        if owner and _posix(destination).lower() not in index:
                            index[_posix(destination).lower()] = owner
                            changed = True
        return index

    def _winmd_target(self, owner: str) -> str:
        """Bazel name of the metadata target for a reference target, which is
        thereby scheduled to be written."""
        winrt = self.report["targets"][owner]["winrt"]
        namespace = _posix(winrt["winmd"]).rsplit("/", 1)[-1][:-len(".winmd")]
        self.winmd_targets[namespace] = owner
        return namespace

    def _winmd_build(self) -> str:
        lines = [MARKER + ".", "",
                 'load("@rules_dotnet//dotnet:defs.bzl", "import_library")',
                 'load("//bazel:winrt.bzl", "winrt_winmd")', "",
                 'package(default_visibility = ["//visibility:public"])']
        done: Set[str] = set()
        pending = sorted(self.winmd_targets)
        while pending:
            namespace = pending.pop(0)
            if namespace in done:
                continue
            done.add(namespace)
            owner = self.winmd_targets[namespace]
            winrt = self.report["targets"][owner]["winrt"]
            references = []
            for ref in winrt.get("references", []):
                other = self.winmd_owner.get(_posix(ref).lower())
                if other:
                    references.append(":" + self._winmd_target(other))
                    pending.append(self._winmd_target(other))
            lines += ["", "# %s: `midl /winrt` + `mdmerge` of its MIDL 3." % owner,
                      "winrt_winmd(", '    name = "%s",' % namespace,
                      "    srcs = %s," % _fmt_list(
                          [self.workspace.label(i, "bazel/winmd") for i in winrt["idl"]]),
                      '    mdmerge = "@windows_sdk//:bin/x64/mdmerge.exe",',
                      '    midl = "@windows_sdk//:bin/x64/midl.exe",',
                      '    namespace = "%s",' % namespace,
                      "    opts = %s," % _fmt_list(winrt.get("midl_options", [])),
                      "    references = %s," % _fmt_list(sorted(references)),
                      '    sdk_winmds = ["@windows_sdk//:winmds"],', ")", "",
                      "# For C# that references the metadata directly (.NET Framework).",
                      "import_library(", '    name = "%s_ref",' % namespace,
                      '    library_name = "%s",' % namespace,
                      '    refs = [":%s"],' % namespace, '    version = "0.0.0",', ")"]
        return "\n".join(lines) + "\n"

    def _cswinrt(self, name: str, package: str, target: str,
                 unhandled: List[str]) -> Optional[dict]:
        """The project's cswinrt invocation as a `cswinrt_projection` target:
        {"name", "starlark", "output"} or None if the project runs none."""
        steps = self.targets[name].get("steps", [])
        execs = [s for s in steps if s.get("kind") == "exec"
                 and "cswinrt.exe" in s.get("command", "").lower()]
        if not execs:
            return None
        command = execs[0]["command"]
        tool = classify_external(_first_token(command))
        m = re.search(r'@"?([^"]+\.rsp)"?', command)
        if not tool or tool.get("kind") != "nuget" or not m:
            unhandled.append("cswinrt invocation that is not `<package>\\cswinrt.exe @file`: %s"
                             % command[:120])
            return None
        rsp = _posix(m.group(1)).lower()
        written = next((s for s in steps if s.get("kind") == "write" and "lines" in s
                        and rsp.endswith(_posix(s["file"]).lower())), None)
        if written is None:
            unhandled.append("cswinrt response file not recorded: %s" % m.group(1))
            return None
        tokens = [a or b for a, b in _RSP_TOKEN.findall(" ".join(written["lines"]))]
        root = (self.reference_root or "").rstrip("\\/")
        includes, excludes, opts, winmds, sdk = [], [], [], [], False
        target_framework, output = "", ""
        # An option takes every value up to the next option: `-input a b c`.
        flag = ""
        for token in tokens:
            if token.startswith("-"):
                flag = token.lower()
                if flag not in ("-target", "-input", "-output", "-include", "-exclude"):
                    opts.append(token)
                    flag = ""
            elif flag == "-target":
                target_framework = token
            elif flag == "-include":
                includes.append(token)
            elif flag == "-exclude":
                excludes.append(token)
            elif flag == "-output":
                output = _relative_to(token, root)
            elif flag == "-input":
                if re.match(r"^(\d+\.\d+\.\d+\.\d+|sdk\+?|local)$", token, re.I):
                    sdk = True
                    continue
                owner = self.winmd_owner.get(_relative_to(token, root).lower())
                packaged = classify_external(token)
                if owner:
                    winmds.append("//bazel/winmd:" + self._winmd_target(owner))
                elif packaged and packaged.get("kind") == "nuget":
                    # Metadata a package ships (Windows App SDK, a COM interop package).
                    winmds.append("@%s//%s/%s:%s" % (self.nuget_repo, packaged["id"],
                                                     packaged["version"], packaged["path"]))
                else:
                    unhandled.append("cswinrt -input that no project of the build produces: %s"
                                     % token)
            else:
                opts.append(token)
        helper = target + "_cswinrt"
        # A short directory: cswinrt.exe silently writes nothing to a path
        # beyond MAX_PATH, and `<package>/<target>_cswinrt.cs/<file>` repeats a
        # long project name twice below Bazel's output base.
        alone = sum(1 for other in self.package.values() if other == package) == 1
        directory = "cswinrt.cs" if alone else "cswinrt_%s.cs" % _sanitize(
            self.targets[name]["csharp"]["target_framework"])
        text = ["# CsWinRT's MSBuild targets run this before the compile (cswinrt.rsp).",
                "cswinrt_projection(", '    name = "%s",' % helper,
                '    out = "%s",' % directory,
                '    cswinrt = "@%s//%s/%s:%s",' % (self.nuget_repo, tool["id"], tool["version"],
                                                    tool["path"]),
                "    excludes = %s," % _fmt_list(excludes),
                "    includes = %s," % _fmt_list(includes)]
        if opts:
            text.append("    opts = %s," % _fmt_list(opts))
        if sdk:
            text.append('    sdk_winmds = ["@windows_sdk//:platform_winmds"],')
        text += ['    target = "%s",' % target_framework,
                 "    winmds = %s," % _fmt_list(sorted(set(winmds))), ")"]
        return {"name": helper, "starlark": "\n".join(text), "output": output,
                "directory": directory}

    def _option_file(self, path: str, package: str, target: str, helpers: List[str],
                     loads: Set[str], unhandled: List[str]) -> Optional[str]:
        """Label for a file a compiler option names (an icon, a manifest). One
        that MSBuild generated into the intermediate directory is restated with
        the reference build's content, like the other files it writes."""
        if not _is_intermediate(path):
            return self.workspace.label(path, package)
        lines = self._read_reference(path)
        if lines is None:
            unhandled.append("generated file %s named by a compiler option: reference file not "
                             "readable; pass --reference-root" % path)
            return None
        base = _posix(path).rsplit("/", 1)[-1]
        helper = "%s_%s" % (target, _sanitize(base))
        helpers.append(_write_file(helper, "_msbuild/%s/%s" % (target, base), lines,
                                   "MSBuild generates this file and names it to the compiler."))
        loads.add("write_file")
        return ":" + helper

    def _resx_linked(self, source: str, package: str) -> List[str]:
        """The `linked` attribute of a resx_resources target, as Starlark lines:
        the files the .resx names by path (`ResXFileRef` entries -- a form's
        icon, an image). The conversion reads them, so they are its inputs."""
        text = None
        for root in (self.workspace.root, self.reference_root):
            if not root:
                continue
            try:
                with open(os.path.join(root, source.replace("/", os.sep)), encoding="utf-8-sig",
                          errors="replace") as f:
                    text = f.read()
                break
            except OSError:
                continue
        if text is None:
            return []
        linked = set()
        for value in _RESX_FILE_REF.findall(text):
            path = value.strip().strip('"').split(";", 1)[0].strip().strip('"')
            if path:
                joined = os.path.normpath(os.path.join(os.path.dirname(source), path.replace("\\", "/")))
                linked.add(self.workspace.label(_posix(joined), package))
        return ["    linked = %s," % _fmt_list(sorted(linked))] if linked else []

    def _plain_resource_name(self, d: dict, path: str, package: str) -> str:
        """The name rules_dotnet gives a file listed in `resources`."""
        relative = _posix(path)[len(package) + 1:] if package and _posix(path).startswith(package + "/") \
            else _posix(path).rsplit("/", 1)[-1]
        return "%s.%s" % (d["assembly"], relative.replace("/", "."))

    def _sdk_analyzers(self, paths: Sequence[str]) -> str:
        """Name of the shared target for a set of analyzers that ship in the
        SDK itself (the same set for every project of one SDK flavour)."""
        key = tuple(sorted(paths))
        if key not in self.sdk_analyzers:
            flavours = sorted({p.split("/")[1].lower().replace("microsoft.net.sdk", "").strip(".")
                               or "net" for p in key if p.count("/") > 1})
            name = "sdk_analyzers_" + "_".join(flavours or ["net"])
            taken = set(self.sdk_analyzers.values())
            self.sdk_analyzers[key] = name if name not in taken else "%s_%d" % (name, len(taken))
        return self.sdk_analyzers[key]

    def _sdk_config(self, path: str) -> str:
        if path not in self.sdk_configs:
            stem = _posix(path).rsplit("/", 1)[-1].rsplit(".", 1)[0]
            self.sdk_configs[path] = "sdk_config_" + _sanitize(stem)
        return self.sdk_configs[path]

    def _shared_build(self) -> str:
        """`bazel/dotnet/BUILD.bazel`: SDK files several targets pass to csc."""
        lines = [MARKER + ".", "",
                 'load("@rules_dotnet//dotnet:defs.bzl", "import_library")',
                 'load(":dotnet_sdk.bzl", "dotnet_sdk_files")', "",
                 'package(default_visibility = ["//visibility:public"])', "",
                 "# What csc_assembly.bzl runs the compiler through.",
                 'exports_files(["csc_wrapper.bat"])']
        for key, name in sorted(self.sdk_analyzers.items(), key=lambda kv: kv[1]):
            lines += ["", "# Analyzers MSBuild adds from the SDK directory itself.",
                      "dotnet_sdk_files(", '    name = "%s_files",' % name,
                      "    paths = %s," % _fmt_list(key), ")", "",
                      "import_library(", '    name = "%s",' % name,
                      '    analyzers = [":%s_files"],' % name,
                      '    library_name = "%s",' % name, '    version = "0.0.0",', ")"]
        for path, name in sorted(self.sdk_configs.items(), key=lambda kv: kv[1]):
            lines += ["", "# Severities the SDK assigns to its analyzers for an analysis level.",
                      "dotnet_sdk_files(", '    name = "%s",' % name,
                      "    paths = %s," % _fmt_list([path]), ")"]
        return "\n".join(lines) + "\n"

    def _input_label(self, f: dict, package: str, unhandled: List[str], what: str) -> str:
        if f["kind"] == "repo":
            return self.workspace.label(f["path"], package)
        if f["kind"] == "nuget":
            return "@%s//%s/%s:%s" % (self.nuget_repo, f["id"], f["version"], f["path"])
        unhandled.append("%s from %s: %s" % (what, f["kind"], f.get("path")))
        return ""

    def _relocate(self, lines: List[str]) -> List[str]:
        """Absolute paths of the reference tree, in a generated config, become
        repo-relative: `build_property.ProjectDir` is where MSBuild ran."""
        if not self.reference_root:
            return lines
        root = self.reference_root.rstrip("\\/")
        out = []
        for line in lines:
            low = line.lower()
            at = low.find(root.lower())
            if at >= 0:
                tail = line[at + len(root):].lstrip("\\/")
                line = line[:at] + _posix(tail)
            out.append(line)
        return out

    def _package_paths(self, lines: List[str]) -> Tuple[List[str], Dict[str, str]]:
        """Absolute paths into NuGet packages, in a generated config, become
        placeholders: (lines, {label of the file: its placeholder})."""
        files: Dict[str, str] = {}

        def replace(match) -> str:
            where = classify_external(match.group(0))
            if not where or where.get("kind") != "nuget":
                return match.group(0)
            label = "@%s//%s/%s:%s" % (self.nuget_repo, where["id"], where["version"], where["path"])
            return files.setdefault(label, "{{%d}}" % len(files))

        return [_ABSOLUTE_PATH.sub(replace, line) for line in lines], files

