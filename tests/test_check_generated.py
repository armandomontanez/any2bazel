"""check_generated.py: what a collapsed tree of generated sources contains.

The fixtures are two small trees on disk. No MSBuild, no Bazel.
"""

import os
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "scripts"))

import check_generated  # noqa: E402
from config import MigrationConfig  # noqa: E402
from reconstruct import CompileGroup, TargetView  # noqa: E402
from model import TargetKind, TargetRole  # noqa: E402

PROJECTION = "src/Engine/obj/Release/net8.0/Generated Files/CsWinRT/"
CFG = MigrationConfig(include_csharp=True, source_map=(
    (PROJECTION, "@cswinrt/Engine"),
    ("bazel-bin/src/Engine/Engine_cswinrt.cs", "@cswinrt/Engine"),
    ("src/Engine/obj/Release/net8.0/Engine.AssemblyInfo.cs", "@msbuild/Engine/assembly_info"),
    ("bazel-bin/src/Engine/_msbuild/Engine/Engine.AssemblyInfo.cs", "@msbuild/Engine/assembly_info"),
))
TREE = "bazel-out/x64_windows-opt-ST-0123456789ab/bin/src/Engine/Engine_cswinrt.cs"
INFO = "bazel-out/x64_windows-opt/bin/src/Engine/_msbuild/Engine/Engine.AssemblyInfo.cs"


def view(*sources):
    return {"Engine": TargetView("Engine", TargetKind.STATIC, TargetRole.PRODUCTION, compile_groups=[
        CompileGroup("Engine", tuple(sources), language="csharp")])}


def write(root, relative, data):
    path = os.path.join(root, relative.replace("/", os.sep))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data if isinstance(data, bytes) else data.encode("utf-8"))


def run(reference_files, bazel_files, reference_sources, bazel_sources=(TREE, INFO)):
    with tempfile.TemporaryDirectory() as ref, tempfile.TemporaryDirectory() as out:
        for relative, data in reference_files.items():
            write(ref, relative, data)
        for relative, data in bazel_files.items():
            write(out, relative, data)
        results = check_generated.compare(
            check_generated.collect(view(*reference_sources), CFG, bazel=False),
            check_generated.collect(view(*bazel_sources), CFG, bazel=True), ref, out)
    return {r["token"]: r for r in results}


def test_the_same_text_is_identical_whatever_its_encoding_and_line_ends():
    # MSBuild's WriteLinesToFile wrote UTF-16 with CRLF and a final newline; the
    # Bazel action wrote UTF-8 with LF. The compiler reads the same text.
    text = "// <auto-generated />\nnamespace A { }"
    results = run(
        {PROJECTION + "A.cs": b"\xff\xfe" + (text.replace("\n", "\r\n") + "\r\n").encode("utf-16-le"),
         "src/Engine/obj/Release/net8.0/Engine.AssemblyInfo.cs": "[assembly: X]\r\n"},
        {TREE + "/A.cs": text, INFO: "[assembly: X]\n"},
        [PROJECTION + "A.cs", "src/Engine/obj/Release/net8.0/Engine.AssemblyInfo.cs"])
    assert {t: r["status"] for t, r in results.items()} == {
        "@cswinrt/Engine": "identical", "@msbuild/Engine/assembly_info": "identical"}
    assert not check_generated.failed(list(results.values()))


def test_a_file_only_the_bazel_tree_has_is_a_mismatch():
    # winget leaves Module.cs out of what it compiles; a rule that copies the
    # whole generator output does not. The command lines cannot tell.
    results = run({PROJECTION + "A.cs": "a"},
                  {TREE + "/A.cs": "a", TREE + "/Module.cs": "[assembly: SupportedOSPlatform]"},
                  [PROJECTION + "A.cs"], [TREE])
    r = results["@cswinrt/Engine"]
    assert (r["status"], r["only_bazel"], r["identical"]) == ("mismatch", ["Module.cs"], 1)
    assert check_generated.failed([r])
    assert "only in bazel: Module.cs" in check_generated.render([r])


def test_a_file_the_bazel_tree_lacks_and_a_changed_line_are_mismatches():
    # One GUID in a projection: the two builds' metadata are not the same.
    results = run({PROJECTION + "A.cs": 'line one\n[Guid("59E19D24")]\n', PROJECTION + "B.cs": "b"},
                  {TREE + "/A.cs": 'line one\n[Guid("CD14CB08")]\n'},
                  [PROJECTION + "A.cs", PROJECTION + "B.cs"], [TREE])
    r = results["@cswinrt/Engine"]
    assert r["only_reference"] == ["B.cs"]
    assert r["different"] == [{"file": "A.cs", "line": 2, "reference": '[Guid("59E19D24")]',
                               "bazel": '[Guid("CD14CB08")]'}]


def test_only_files_the_reference_compiled_count_not_everything_in_its_directory():
    # The generator's directory also holds its response file, and may hold
    # sources the project removes from the compile.
    results = run({PROJECTION + "A.cs": "a", PROJECTION + "cswinrt.rsp": "-input x",
                   PROJECTION + "Module.cs": "not compiled"},
                  {TREE + "/A.cs": "a"}, [PROJECTION + "A.cs"], [TREE])
    assert results["@cswinrt/Engine"]["status"] == "identical"


def test_single_files_pair_whatever_they_are_called():
    token = "@msbuild/Engine/assembly_info"
    cfg_sources = ["src/Engine/obj/Release/net8.0/Engine.AssemblyInfo.cs"]
    results = run({cfg_sources[0]: "[assembly: A]\n"}, {INFO: "[assembly: B]\n"}, cfg_sources, [INFO])
    assert results[token]["status"] == "mismatch"
    assert results[token]["different"][0]["line"] == 1


def test_a_tree_that_was_not_built_fails_and_a_one_sided_token_is_left_to_the_diff():
    results = run({PROJECTION + "A.cs": "a"}, {}, [PROJECTION + "A.cs"], [TREE])
    r = results["@cswinrt/Engine"]
    assert (r["status"], r["not_found"]) == ("mismatch", [TREE])
    results = run({PROJECTION + "A.cs": "a"}, {}, [PROJECTION + "A.cs"], [])
    assert results["@cswinrt/Engine"]["status"] == "one_side_only"
    assert not check_generated.failed(list(results.values()))


def test_resources_embedded_under_the_same_name_are_compared_byte_for_byte():
    import canonicalize_csc as csc

    def assembly(resource_path, out):
        args = ["csc.exe", "/target:library", "/out:" + out,
                "/resource:%s,Engine.Strings.resources" % resource_path, "A.cs"]
        group = CompileGroup("Engine", ("A.cs",), language="csharp", csc=csc.parse(args))
        return {"Engine": TargetView("Engine", TargetKind.STATIC, TargetRole.PRODUCTION,
                                     compile_groups=[group])}

    ref_path, bazel_path = "src/Engine/obj/Engine.Strings.resources", "bazel-out/x/bin/src/Engine/Strings.resources"
    a = assembly(ref_path, "obj/net8.0/Engine.dll")
    b = assembly(bazel_path, "bazel-out/x/bin/src/Engine/Engine/net8.0/Engine.dll")
    for theirs, ours, status in ((b"\xce\xca\xef\xbe same", b"\xce\xca\xef\xbe same", "identical"),
                                 (b"\xce\xca\xef\xbe one", b"\xce\xca\xef\xbe two", "mismatch")):
        with tempfile.TemporaryDirectory() as ref, tempfile.TemporaryDirectory() as out:
            write(ref, ref_path, theirs)
            write(out, bazel_path, ours)
            (record,) = check_generated.compare_resources(a, b, CFG, ref, out)
        assert record["status"] == status and record["token"].startswith("resources of Engine")
    assert record["different"] == [{"file": "Engine.Strings.resources"}]


